package gezi.narrowblocks.groups

import java.lang.classfile.ClassBuilder
import java.lang.classfile.ClassFile
import java.lang.classfile.CodeBuilder
import java.lang.classfile.TypeKind
import java.lang.constant.ClassDesc
import java.lang.constant.ConstantDescs
import java.lang.constant.MethodTypeDesc
import java.lang.invoke.MethodHandle
import java.lang.invoke.MethodHandles

/** The kernels of the JVM array group backend:
  * static methods over `int[]` of one generated class, each a counting loop
  * whose body is straight-line code, so that HotSpot's C2 compiles it to
  * vector instructions where it can.
  *
  * THE ARRAYS ARE WRITTEN. A kernel allocates its result array (an `int[]`
  * or a `long[]`) before the loop and writes it cell by cell, by increments
  * at the cells its input names (`histogram`), or by sorting its own copy of
  * the input in place (`sortedUnique`): the most efficient structure, and
  * the shape C2 vectorizes, an exception to the immutability of the code
  * (`CONTRIBUTING.md`, "The code is 100% immutable"). The exception is the
  * generated bytecode's only: a kernel writes only the array it allocated,
  * before it returns it, and the Scala code holds the result as an `IArray`
  * and never writes it.
  *
  * WHICH KERNELS VECTORIZE, measured on OpenJDK 25 with AVX2 and pinned by
  * `JvmArrayKernelsSimdTest`: the elementwise sum, difference, product and
  * negation (256-bit lanes); the comparisons, as 0 or 1 in an `int[]` by
  * branch-free arithmetic (a `boolean[]` result, a narrowing, or a
  * conditional move does not vectorize); the left factor of an outer
  * product, a broadcast store per row. The gather by row numbers and the
  * selection of rows do not: C2 emits no gather instruction, and a
  * selection's count of kept rows is a branch. The right factor of an outer
  * product copies a row with `System.arraycopy`, whose stub copies with
  * vector moves. Packing two int columns into longs and taking them apart
  * again vectorize (64-bit shifts, 256-bit lanes), and so does filling a
  * column with one value; the merge join, the histogram's increments at the
  * cells its input names, the first row of each rank, the dropping of
  * adjacent duplicates after the sort and the ranking by a binary search
  * per key do not, each a branch, a scatter or a call.
  *
  * The class is generated once, when the backend is first used, and defined
  * as a hidden class of this package; `classBytes` gives the same bytes, so
  * that a test can load them in a fresh JVM under a fixed name.
  */
object JvmArrayKernels:

  /** The binary name the generated class is defined under, before the
    * hidden class's suffix.
    */
  val className: String = "gezi.narrowblocks.groups.JvmArrayKernelClass"

  private val generatedClass: ClassDesc = ClassDesc.of(className)

  private val intArray: ClassDesc = ConstantDescs.CD_int.arrayType()

  private val unaryType: MethodTypeDesc = MethodTypeDesc.of(intArray, intArray)

  private val binaryType: MethodTypeDesc = MethodTypeDesc.of(intArray, intArray, intArray)

  private val countType: MethodTypeDesc = MethodTypeDesc.of(intArray, ConstantDescs.CD_int)

  private val shapeType: MethodTypeDesc = MethodTypeDesc.of(intArray, ConstantDescs.CD_int, ConstantDescs.CD_int)

  private val longArray: ClassDesc = ConstantDescs.CD_long.arrayType()

  private val packedType: MethodTypeDesc = MethodTypeDesc.of(longArray, intArray, ConstantDescs.CD_int, intArray, ConstantDescs.CD_int)

  private val unpackedType: MethodTypeDesc = MethodTypeDesc.of(intArray, longArray, ConstantDescs.CD_int)

  private val keysType: MethodTypeDesc = MethodTypeDesc.of(longArray, longArray)

  private val pairedType: MethodTypeDesc = MethodTypeDesc.of(longArray, longArray, longArray)

  private val histogramType: MethodTypeDesc = MethodTypeDesc.of(intArray, intArray, ConstantDescs.CD_int)

  private val rankedType: MethodTypeDesc = MethodTypeDesc.of(intArray, longArray, longArray)

  /** The sign bit, which turns an unsigned comparison of ints into a signed
    * one and back.
    */
  private val signBit: Int = Integer.MIN_VALUE

  /** The elementwise operations on two arrays, by their method names, each
    * leaving its value on the stack from the operands in the slots 5 and 6
    * (slot 7 free): the sum, difference and product modulo 2³²; whether the
    * two are equal, and whether the left is below the right as two's
    * complement words, as 1 or 0, by branch-free arithmetic.
    */
  private val elementwise: Vector[(String, CodeBuilder => Unit)] = Vector(
    "added" -> (code => code.iload(5).iload(6).iadd()),
    "subtracted" -> (code => code.iload(5).iload(6).isub()),
    "multiplied" -> (code => code.iload(5).iload(6).imul()),
    // x = a ^ b; ((x | -x) >>> 31) ^ 1
    "equal" -> (code => code.iload(5).iload(6).ixor().istore(7).iload(7).iload(7).ineg().ior().bipush(31).iushr().iconst_1().ixor()),
    // d = a - b; (d ^ ((a ^ b) & (d ^ a))) >>> 31
    "lessThan" -> (code =>
      code.iload(5).iload(6).isub().istore(7)
      code.iload(7).iload(5).iload(6).ixor().iload(7).iload(5).ixor().iand().ixor().bipush(31).iushr()
    ),
  )

  /** The names of the kernels C2 is expected to compile to vector
    * instructions, with the instruction each is expected to hold.
    */
  val expectedVectorInstructions: Vector[(String, String)] = Vector(
    "added" -> "vpaddd",
    "subtracted" -> "vpsubd",
    "multiplied" -> "vpmulld",
    "negated" -> "vpsubd",
    "equal" -> "vpor",
    "lessThan" -> "vpand",
    "repeated" -> "vpbroadcastd"
  )

  /** The class file of the kernels. */
  lazy val classBytes: Array[Byte] =
    ClassFile
      .of()
      .build(
        generatedClass,
        (classBuilder: ClassBuilder) =>
          classBuilder.withFlags(ClassFile.ACC_PUBLIC | ClassFile.ACC_FINAL)
          classBuilder.withMethodBody("iota", countType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, iotaEmitted)
          classBuilder.withMethodBody("gathered", binaryType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, gatheredEmitted)
          classBuilder.withMethodBody("repeated", shapeType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, repeatedEmitted)
          classBuilder.withMethodBody("tiled", shapeType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, tiledEmitted)
          classBuilder.withMethodBody("concatenated", binaryType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, concatenatedEmitted)
          classBuilder.withMethodBody("negated", unaryType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, negatedEmitted)
          classBuilder.withMethodBody("compressed", unaryType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, compressedEmitted(selectedWhenZero = false))
          classBuilder.withMethodBody("compressedZeros", unaryType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, compressedEmitted(selectedWhenZero = true))
          classBuilder.withMethodBody("packed", packedType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, packedEmitted)
          classBuilder.withMethodBody("high", unpackedType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, unpackedEmitted(high = true))
          classBuilder.withMethodBody("low", unpackedType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, unpackedEmitted(high = false))
          classBuilder.withMethodBody("sortedUnique", keysType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, sortedUniqueEmitted)
          classBuilder.withMethodBody("mergeJoined", pairedType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, mergeJoinedEmitted)
          classBuilder.withMethodBody("histogram", histogramType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, histogramEmitted)
          classBuilder.withMethodBody("filled", shapeType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, filledEmitted)
          classBuilder.withMethodBody("ranked", rankedType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, rankedEmitted)
          classBuilder.withMethodBody("firstRows", histogramType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, firstRowsEmitted)
          elementwise.foreach((name, operation) =>
            classBuilder.withMethodBody(name, binaryType, ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC, binaryKernel(operation))
          )
          ()
      )

  /** The loop `for (int counter = 0; counter < limit; counter++) body`,
    * the counter and the limit in the slots given.
    */
  private def counted(code: CodeBuilder, counter: Int, limit: Int)(body: => Unit): Unit =
    val head = code.newLabel()
    val end = code.newLabel()
    code.iconst_0().istore(counter)
    code.labelBinding(head)
    code.iload(counter).iload(limit).if_icmpge(end)
    body
    code.iinc(counter, 1).goto_(head)
    code.labelBinding(end)
    ()

  /** The loop `for (int counter = start; counter < limit; counter++) body`,
    * the counter, the start and the limit in the slots given.
    */
  private def ranged(code: CodeBuilder, counter: Int, start: Int, limit: Int)(body: => Unit): Unit =
    val head = code.newLabel()
    val end = code.newLabel()
    code.iload(start).istore(counter)
    code.labelBinding(head)
    code.iload(counter).iload(limit).if_icmpge(end)
    body
    code.iinc(counter, 1).goto_(head)
    code.labelBinding(end)
    ()

  /** iota(n): o[i] = i. Slots: n 0, o 1, i 2. */
  private def iotaEmitted(code: CodeBuilder): Unit =
    code.iload(0).newarray(TypeKind.INT).astore(1)
    counted(code, 2, 0)(code.aload(1).iload(2).iload(2).iastore())
    code.aload(1).areturn()
    ()

  /** gathered(column, rows): o[i] = column[rows[i]]. Slots: column 0, rows
    * 1, n 2, o 3, i 4.
    */
  private def gatheredEmitted(code: CodeBuilder): Unit =
    code.aload(1).arraylength().istore(2)
    code.iload(2).newarray(TypeKind.INT).astore(3)
    counted(code, 4, 2)(code.aload(3).iload(4).aload(0).aload(1).iload(4).iaload().iaload().iastore())
    code.aload(3).areturn()
    ()

  /** repeated(n, width): each row number below n, width times in a row, the
    * left factor of an outer product; the inner loop fills one constant.
    * Slots: n 0, width 1, o 2, i 3, base 4, j 5, end 6.
    */
  private def repeatedEmitted(code: CodeBuilder): Unit =
    code.iload(0).iload(1).imul().newarray(TypeKind.INT).astore(2)
    counted(code, 3, 0) {
      code.iload(3).iload(1).imul().istore(4)
      counted(code, 5, 1)(code.aload(2).iload(4).iload(5).iadd().iload(3).iastore())
    }
    code.aload(2).areturn()
    ()

  /** tiled(n, height): the row numbers below n, height times over, the right
    * factor of an outer product; each copy by `System.arraycopy`. Slots: n 0,
    * height 1, base 2, o 3, k 4.
    */
  private def tiledEmitted(code: CodeBuilder): Unit =
    code.iload(0).invokestatic(generatedClass, "iota", countType).astore(2)
    code.iload(0).iload(1).imul().newarray(TypeKind.INT).astore(3)
    counted(code, 4, 1) {
      code.aload(2).iconst_0().aload(3).iload(4).iload(0).imul().iload(0)
      code.invokestatic(ClassDesc.of("java.lang.System"), "arraycopy", arraycopyType)
    }
    code.aload(3).areturn()
    ()

  private val arraycopyType: MethodTypeDesc =
    MethodTypeDesc.of(ConstantDescs.CD_void, ConstantDescs.CD_Object, ConstantDescs.CD_int, ConstantDescs.CD_Object, ConstantDescs.CD_int, ConstantDescs.CD_int)

  /** concatenated(left, right): the left's cells then the right's. Slots:
    * left 0, right 1, o 2.
    */
  private def concatenatedEmitted(code: CodeBuilder): Unit =
    code.aload(0).arraylength().aload(1).arraylength().iadd().newarray(TypeKind.INT).astore(2)
    code.aload(0).iconst_0().aload(2).iconst_0().aload(0).arraylength()
    code.invokestatic(ClassDesc.of("java.lang.System"), "arraycopy", arraycopyType)
    code.aload(1).iconst_0().aload(2).aload(0).arraylength().aload(1).arraylength()
    code.invokestatic(ClassDesc.of("java.lang.System"), "arraycopy", arraycopyType)
    code.aload(2).areturn()
    ()

  /** negated(values): o[i] = -values[i]. Slots: values 0, n 1, o 2, i 3. */
  private def negatedEmitted(code: CodeBuilder): Unit =
    code.aload(0).arraylength().istore(1)
    code.iload(1).newarray(TypeKind.INT).astore(2)
    counted(code, 3, 1)(code.aload(2).iload(3).aload(0).iload(3).iaload().ineg().iastore())
    code.aload(2).areturn()
    ()

  /** compressed(mask): the positions whose cell is not 0, in order, or
    * compressedZeros(mask), those whose cell is 0: one loop counts them, the
    * second writes them. Slots: mask 0, n 1, count 2, i 3, o 4, k 5.
    */
  private def compressedEmitted(selectedWhenZero: Boolean)(code: CodeBuilder): Unit =
    // The cell's test on the stack: the cell itself (not 0 selects), or
    // whether it is 0 (`iconst_1 ixor` of its truth, the cells being 0 or 1).
    def tested(): Unit =
      code.aload(0).iload(3).iaload()
      if selectedWhenZero then code.iconst_1().ixor()
      ()
    code.aload(0).arraylength().istore(1)
    code.iconst_0().istore(2)
    counted(code, 3, 1) {
      tested()
      code.ifThen((inner: java.lang.classfile.CodeBuilder.BlockCodeBuilder) => { inner.iinc(2, 1); () })
    }
    code.iload(2).newarray(TypeKind.INT).astore(4)
    code.iconst_0().istore(5)
    counted(code, 3, 1) {
      tested()
      code.ifThen((inner: java.lang.classfile.CodeBuilder.BlockCodeBuilder) => {
        inner.aload(4).iload(5).iload(3).iastore().iinc(5, 1); ()
      })
    }
    code.aload(4).areturn()
    ()

  /** Pushes the packed key of two ints on the stack, the ints' order keys
    * on the stack top and below it: the first in the high 32 bits, the
    * second, its sign bit flipped, in the low 32 bits, so that the signed
    * order of the longs is the order of the pairs, the first first.
    */
  private def packTop(code: CodeBuilder, first: Int, second: Int): Unit =
    code.iload(first).i2l().bipush(32).lshl()
    code.iload(second).ldc(Integer.valueOf(signBit)).ixor().i2l().ldc(java.lang.Long.valueOf(0xffffffffL)).land().lor()
    ()

  /** packed(a, flipA, b, flipB): o[i] = the packed key of a[i] ^ flipA and
    * b[i] ^ flipB, each flip the sign bit for a column of ints ordered
    * unsigned and 0 otherwise, so that the longs' signed order is the rows'
    * canonical order (`GroupBackend.rowOrdering`). Slots: a 0, flipA 1, b 2,
    * flipB 3, n 4, o 5, i 6, x 7, y 8.
    */
  private def packedEmitted(code: CodeBuilder): Unit =
    code.aload(0).arraylength().istore(4)
    code.iload(4).newarray(TypeKind.LONG).astore(5)
    counted(code, 6, 4) {
      code.aload(0).iload(6).iaload().iload(1).ixor().istore(7)
      code.aload(2).iload(6).iaload().iload(3).ixor().istore(8)
      code.aload(5).iload(6)
      packTop(code, 7, 8)
      code.lastore()
    }
    code.aload(5).areturn()
    ()

  /** high(keys, flip) or low(keys, flip): the first or the second int of
    * each packed key, its flip undone. Slots: keys 0, flip 1, n 2, o 3, i 4.
    */
  private def unpackedEmitted(high: Boolean)(code: CodeBuilder): Unit =
    code.aload(0).arraylength().istore(2)
    code.iload(2).newarray(TypeKind.INT).astore(3)
    counted(code, 4, 2) {
      code.aload(3).iload(4).aload(0).iload(4).laload()
      if high then code.bipush(32).lshr().l2i()
      else code.l2i().ldc(Integer.valueOf(signBit)).ixor()
      code.iload(1).ixor().iastore()
    }
    code.aload(3).areturn()
    ()

  /** sortedUnique(keys): the distinct keys in ascending order: a copy sorted
    * in place (the copy is the kernel's own array, before it is returned),
    * then the adjacent duplicates dropped, one loop counting, one writing.
    * Slots: keys 0, n 1, s 2, count 3, i 4, o 5, k 6.
    */
  private def sortedUniqueEmitted(code: CodeBuilder): Unit =
    val system = ClassDesc.of("java.lang.System")
    code.aload(0).arraylength().istore(1)
    code.iload(1).newarray(TypeKind.LONG).astore(2)
    code.aload(0).iconst_0().aload(2).iconst_0().iload(1).invokestatic(system, "arraycopy", arraycopyType)
    code.aload(2).invokestatic(ClassDesc.of("java.util.Arrays"), "sort", MethodTypeDesc.of(ConstantDescs.CD_void, longArray))
    // A cell is kept when it is the first or differs from the one before.
    def kept(body: java.lang.classfile.CodeBuilder.BlockCodeBuilder => Unit): Unit =
      val keep = code.newLabel()
      val skip = code.newLabel()
      code.iload(4).ifeq(keep)
      code.aload(2).iload(4).laload().aload(2).iload(4).iconst_1().isub().laload().lcmp().ifeq(skip)
      code.labelBinding(keep)
      code.block((inner: java.lang.classfile.CodeBuilder.BlockCodeBuilder) => body(inner))
      code.labelBinding(skip)
      ()
    code.iconst_0().istore(3)
    counted(code, 4, 1)(kept(inner => { inner.iinc(3, 1); () }))
    code.iload(3).newarray(TypeKind.LONG).astore(5)
    code.iconst_0().istore(6)
    counted(code, 4, 1)(kept(inner => { inner.aload(5).iload(6).aload(2).iload(4).laload().lastore().iinc(6, 1); () }))
    code.aload(5).areturn()
    ()

  /** mergeJoined(left, right): both packed keys sorted ascending, each a key
    * in its high int and a row's position in its low int (`packed` of the
    * key column and the row numbers); the pairs of positions whose keys are
    * equal, each packed (left high, right low), in no order. One pass counts
    * the pairs, the second writes them: in each, the two cursors advance past
    * the smaller key, and at equal keys each side's run of that key is
    * found and every pair of the runs taken.
    * Slots: left 0, right 1, nl 2, nr 3, i 4, j 5, count 6, kl 7, kr 8,
    * i2 9, j2 10, out 11, k 12, a 13, b 14, x 15, y 16.
    */
  private def mergeJoinedEmitted(code: CodeBuilder): Unit =
    def keyAt(array: Int, index: Int): Unit =
      code.aload(array).iload(index).laload().bipush(32).lshr().l2i()
      ()
    def positionAt(array: Int, index: Int): Unit =
      code.aload(array).iload(index).laload().l2i().ldc(Integer.valueOf(signBit)).ixor()
      ()
    def merged(fill: Boolean): Unit =
      val head = code.newLabel()
      val end = code.newLabel()
      val leftSmaller = code.newLabel()
      val rightSmaller = code.newLabel()
      code.iconst_0().istore(4).iconst_0().istore(5)
      code.labelBinding(head)
      code.iload(4).iload(2).if_icmpge(end)
      code.iload(5).iload(3).if_icmpge(end)
      keyAt(0, 4); code.istore(7)
      keyAt(1, 5); code.istore(8)
      code.iload(7).iload(8).if_icmplt(leftSmaller)
      code.iload(7).iload(8).if_icmpgt(rightSmaller)
      // Equal keys: the runs [i, i2) and [j, j2).
      def runEnd(array: Int, start: Int, limit: Int, finish: Int): Unit =
        val scan = code.newLabel()
        val done = code.newLabel()
        code.iload(start).istore(finish)
        code.labelBinding(scan)
        code.iload(finish).iload(limit).if_icmpge(done)
        keyAt(array, finish); code.iload(7).if_icmpne(done)
        code.iinc(finish, 1).goto_(scan)
        code.labelBinding(done)
        ()
      runEnd(0, 4, 2, 9)
      runEnd(1, 5, 3, 10)
      if !fill then
        code.iload(6).iload(9).iload(4).isub().iload(10).iload(5).isub().imul().iadd().istore(6)
      else
        ranged(code, 13, 4, 9) {
          ranged(code, 14, 5, 10) {
            positionAt(0, 13); code.istore(15)
            positionAt(1, 14); code.istore(16)
            code.aload(11).iload(12)
            packTop(code, 15, 16)
            code.lastore().iinc(12, 1)
          }
        }
      code.iload(9).istore(4).iload(10).istore(5)
      code.goto_(head)
      code.labelBinding(leftSmaller)
      code.iinc(4, 1).goto_(head)
      code.labelBinding(rightSmaller)
      code.iinc(5, 1).goto_(head)
      code.labelBinding(end)
      ()
    code.aload(0).arraylength().istore(2)
    code.aload(1).arraylength().istore(3)
    code.iconst_0().istore(6)
    merged(fill = false)
    code.iload(6).newarray(TypeKind.LONG).astore(11)
    code.iconst_0().istore(12)
    merged(fill = true)
    code.aload(11).areturn()
    ()

  /** histogram(rows, count): o[r] = how many cells of rows are r, for r
    * below count, every cell of rows being one of them. Slots: rows 0,
    * count 1, o 2, n 3, i 4, r 5.
    */
  private def histogramEmitted(code: CodeBuilder): Unit =
    code.iload(1).newarray(TypeKind.INT).astore(2)
    code.aload(0).arraylength().istore(3)
    counted(code, 4, 3) {
      code.aload(0).iload(4).iaload().istore(5)
      code.aload(2).iload(5).aload(2).iload(5).iaload().iconst_1().iadd().iastore()
    }
    code.aload(2).areturn()
    ()

  /** filled(n, value): o[i] = value, n cells. Slots: n 0, value 1, o 2,
    * i 3.
    */
  private def filledEmitted(code: CodeBuilder): Unit =
    code.iload(0).newarray(TypeKind.INT).astore(2)
    counted(code, 3, 0)(code.aload(2).iload(3).iload(1).iastore())
    code.aload(2).areturn()
    ()

  /** ranked(keys, distinct): o[i] = the position of keys[i] in distinct,
    * the keys' distinct values ascending (`sortedUnique`), by
    * `java.util.Arrays.binarySearch`. Slots: keys 0, distinct 1, n 2, o 3,
    * i 4.
    */
  private def rankedEmitted(code: CodeBuilder): Unit =
    code.aload(0).arraylength().istore(2)
    code.iload(2).newarray(TypeKind.INT).astore(3)
    counted(code, 4, 2) {
      code.aload(3).iload(4).aload(1).aload(0).iload(4).laload()
      code.invokestatic(ClassDesc.of("java.util.Arrays"), "binarySearch", MethodTypeDesc.of(ConstantDescs.CD_int, longArray, ConstantDescs.CD_long))
      code.iastore()
    }
    code.aload(3).areturn()
    ()

  /** firstRows(ranks, count): o[r] = the first position whose rank is r,
    * for r below count, every rank below count and each one held somewhere:
    * the positions written from the last to the first, so the first stays.
    * Slots: ranks 0, count 1, o 2, i 3.
    */
  private def firstRowsEmitted(code: CodeBuilder): Unit =
    val head = code.newLabel()
    val end = code.newLabel()
    code.iload(1).newarray(TypeKind.INT).astore(2)
    code.aload(0).arraylength().istore(3)
    code.labelBinding(head)
    code.iload(3).ifle(end)
    code.iinc(3, -1)
    code.aload(2).aload(0).iload(3).iaload().iload(3).iastore()
    code.goto_(head)
    code.labelBinding(end)
    code.aload(2).areturn()
    ()

  /** An elementwise kernel on two arrays of one length: o[i] = op(left[i],
    * right[i]), the operands in the slots 5 and 6. Slots: left 0, right 1,
    * n 2, o 3, i 4, a 5, b 6, a temporary 7.
    */
  private def binaryKernel(operation: CodeBuilder => Unit)(code: CodeBuilder): Unit =
    code.aload(0).arraylength().istore(2)
    code.iload(2).newarray(TypeKind.INT).astore(3)
    counted(code, 4, 2) {
      code.aload(0).iload(4).iaload().istore(5)
      code.aload(1).iload(4).iaload().istore(6)
      code.aload(3).iload(4)
      operation(code)
      code.iastore()
    }
    code.aload(3).areturn()
    ()

  /** The lookup of the generated class, defined as a hidden class of this
    * package, with full access to it.
    */
  private lazy val defined: MethodHandles.Lookup = MethodHandles.lookup().defineHiddenClass(classBytes, true)

  private def handle(name: String, descriptor: MethodTypeDesc): MethodHandle =
    defined.findStatic(defined.lookupClass(), name, descriptor.resolveConstantDesc(defined))

  private lazy val handles: Map[String, MethodHandle] =
    (Vector("iota" -> countType, "repeated" -> shapeType, "tiled" -> shapeType, "gathered" -> binaryType, "concatenated" -> binaryType)
      ++ Vector("negated" -> unaryType, "compressed" -> unaryType, "compressedZeros" -> unaryType)
      ++ Vector("packed" -> packedType, "high" -> unpackedType, "low" -> unpackedType, "sortedUnique" -> keysType, "mergeJoined" -> pairedType)
      ++ Vector("histogram" -> histogramType, "filled" -> shapeType, "ranked" -> rankedType, "firstRows" -> histogramType)
      ++ elementwise.map((name, _) => name -> binaryType)).map((name, descriptor) => name -> handle(name, descriptor)).toMap

  /** The array a kernel returned, held immutable from now on: the kernel
    * wrote it and returned it, and no code writes it again.
    */
  private def held(result: AnyRef): IArray[Int] = result match
    case array: Array[Int] => IArray.unsafeFromArray(array)
    case other             => throw IllegalStateException(s"a kernel returns an int[], not $other")

  private def called(name: String, arguments: AnyRef*): IArray[Int] =
    held(handles.getOrElse(name, throw IllegalArgumentException(s"no kernel $name")).invokeWithArguments(arguments*))

  /** The array of longs a kernel returned, held immutable from now on. */
  private def heldLongs(result: AnyRef): IArray[Long] = result match
    case array: Array[Long] => IArray.unsafeFromArray(array)
    case other              => throw IllegalStateException(s"a kernel returns a long[], not $other")

  private def calledLongs(name: String, arguments: AnyRef*): IArray[Long] =
    heldLongs(handles.getOrElse(name, throw IllegalArgumentException(s"no kernel $name")).invokeWithArguments(arguments*))

  /** The packed keys of two columns of one length, each with its flip: the
    * sign bit for a column of ints ordered unsigned, 0 for one ordered
    * signed (row numbers, truths as 0 or 1).
    */
  def packed(first: IArray[Int], firstFlip: Int, second: IArray[Int], secondFlip: Int): IArray[Long] =
    require(first.length == second.length, s"packed columns have one length: ${first.length} and ${second.length}")
    calledLongs("packed", first.asInstanceOf[AnyRef], Integer.valueOf(firstFlip), second.asInstanceOf[AnyRef], Integer.valueOf(secondFlip))

  /** The first ints of the packed keys, their flip undone. */
  def high(keys: IArray[Long], flip: Int): IArray[Int] = called("high", keys.asInstanceOf[AnyRef], Integer.valueOf(flip))

  /** The second ints of the packed keys, their flip undone. */
  def low(keys: IArray[Long], flip: Int): IArray[Int] = called("low", keys.asInstanceOf[AnyRef], Integer.valueOf(flip))

  /** The distinct keys, ascending. */
  def sortedUnique(keys: IArray[Long]): IArray[Long] = calledLongs("sortedUnique", keys.asInstanceOf[AnyRef])

  /** The pairs of positions whose keys are equal, of two key columns each
    * packed with its row numbers and sorted (`packed`, `sortedUnique`):
    * each pair packed, the left's position first, in no order.
    */
  def mergeJoined(left: IArray[Long], right: IArray[Long]): IArray[Long] =
    calledLongs("mergeJoined", left.asInstanceOf[AnyRef], right.asInstanceOf[AnyRef])

  /** `count` cells of the value. */
  def filled(count: Int, value: Int): IArray[Int] = called("filled", Integer.valueOf(count), Integer.valueOf(value))

  /** Each key's position among the distinct keys, ascending
    * (`sortedUnique` of a superset of the keys).
    */
  def ranked(keys: IArray[Long], distinct: IArray[Long]): IArray[Int] = called("ranked", keys.asInstanceOf[AnyRef], distinct.asInstanceOf[AnyRef])

  /** For each rank below `count`, the first position that holds it; every
    * rank below `count` is held.
    */
  def firstRows(ranks: IArray[Int], count: Int): IArray[Int] = called("firstRows", ranks.asInstanceOf[AnyRef], Integer.valueOf(count))

  /** How many cells of the row numbers are each row below `count`. */
  def histogram(rows: IArray[Int], count: Int): IArray[Int] = called("histogram", rows.asInstanceOf[AnyRef], Integer.valueOf(count))

  /** The sign bit, the flip of a column of ints ordered unsigned. */
  val unsignedFlip: Int = signBit

  /** The row numbers below n. */
  def iota(count: Int): IArray[Int] = called("iota", Integer.valueOf(count))

  /** The column's cells at the rows, in their order. */
  def gathered(column: IArray[Int], rows: IArray[Int]): IArray[Int] = called("gathered", column.asInstanceOf[AnyRef], rows.asInstanceOf[AnyRef])

  /** Each row number below `count`, `width` times in a row. */
  def repeated(count: Int, width: Int): IArray[Int] = called("repeated", Integer.valueOf(count), Integer.valueOf(width))

  /** The row numbers below `count`, `height` times over. */
  def tiled(count: Int, height: Int): IArray[Int] = called("tiled", Integer.valueOf(count), Integer.valueOf(height))

  /** The left's cells then the right's. */
  def concatenated(left: IArray[Int], right: IArray[Int]): IArray[Int] = called("concatenated", left.asInstanceOf[AnyRef], right.asInstanceOf[AnyRef])

  /** The negation of each cell modulo 2³². */
  def negated(values: IArray[Int]): IArray[Int] = called("negated", values.asInstanceOf[AnyRef])

  /** The positions whose cell is not 0. */
  def compressed(mask: IArray[Int]): IArray[Int] = called("compressed", mask.asInstanceOf[AnyRef])

  /** The positions whose cell is 0, of a mask of cells 0 or 1. */
  def compressedZeros(mask: IArray[Int]): IArray[Int] = called("compressedZeros", mask.asInstanceOf[AnyRef])

  /** The elementwise operation of the name (`added`, `subtracted`,
    * `multiplied`, `equal`, `lessThan`) on two columns of one length.
    */
  def elementwiseOf(name: String, left: IArray[Int], right: IArray[Int]): IArray[Int] =
    require(left.length == right.length, s"an elementwise kernel takes two columns of one length: ${left.length} and ${right.length}")
    called(name, left.asInstanceOf[AnyRef], right.asInstanceOf[AnyRef])

  /** The names of the elementwise kernels. */
  val elementwiseNames: Vector[String] = elementwise.map(_._1)
