package gezi.narrowblocks

/** The opt-in copy of the narrow blocks with lists and booleans ([[gezi.narrowblocks.lists]]), selected by `ExtractorImplementation.NarrowListBlock`. */
package lists

import java.math.BigInteger

/** A narrow list at run time ([[gezi.narrowblocks.lists]], THE LIST KIND):
  * the suffix from `start` of a list of narrow naturals decoded
  * once, at compile time, from a filtered list literal
  * (`NarrowBlockCompilation.listDecoded`). Its tail is the same elements at
  * `start + 1`, so every suffix shares the elements, and it is nil when
  * `start` is the number of the elements. A narrow block's value is a
  * `BigInteger` or a `NarrowList`; the generated code tells them apart where
  * it reads a value as one of them.
  *
  * The generated bytecode calls `nil`, `head`, `tail` and `remaining` by name, as it calls
  * `BigInteger`'s methods: a name changed here is changed in
  * `NarrowBlockCompilation` too.
  */
final case class NarrowList(elements: Vector[BigInteger], start: Int):
  require(start >= 0 && start <= elements.size, s"a suffix starts within its list: $start of ${elements.size}")

  /** Whether the suffix is empty. */
  def nil: Boolean = start == elements.size

  /** The suffix's elements, what a native's `NativePlace.NaturalList` takes. */
  def remaining: Vector[BigInteger] = elements.drop(start)

  /** The suffix's first element. Throws `IllegalStateException` on nil, a
    * defect of the caller, which reads it only after `nil` is false.
    */
  def head: BigInteger =
    if nil then throw IllegalStateException("the head of an empty narrow list") else elements(start)

  /** The suffix after the first element. Throws `IllegalStateException` on
    * nil, as `head` does.
    */
  def tail: NarrowList =
    if nil then throw IllegalStateException("the tail of an empty narrow list") else NarrowList(elements, start + 1)

/** A list of records of a declared data family at run time, decoded once, at
  * compile time, from a filtered literal
  * (`NarrowBlockCompilation.recordListDecoded`): one column of naturals per
  * field, all of one length. Only a native's `NativePlace.NaturalRecordList`
  * reads it. It compares by reference, the default of a plain class, so that a
  * memo key holding it is a decode point: two equal lists are two keys, a miss
  * and never a wrong hit.
  *
  * The generated bytecode calls `columns` by name.
  */
final class NarrowRecords(val columns: Vector[Vector[BigInteger]])

/** A constant a narrow block reads, decoded at compile time and held in the
  * generated class's data: a narrow natural, a narrow list, a boolean or a
  * list of records.
  */
enum NarrowConstant:
  case Natural(value: BigInt)
  case ListOf(list: NarrowList)
  case Truth(value: Boolean)
  case RecordsOf(records: NarrowRecords)

  /** The value the generated code loads: a `BigInteger`, a `NarrowList`, a
    * `java.lang.Boolean` or a `NarrowRecords`.
    */
  def runtimeValue: AnyRef = this match
    case Natural(value)     => value.bigInteger
    case ListOf(list)       => list
    case Truth(value)       => java.lang.Boolean.valueOf(value)
    case RecordsOf(records) => records
