/** A narrow block compiled into a class: its natural, or nothing when `stop`
  * asked for a stop before the block finished (`run`). The signal is read on
  * entry to every recursion's method, once per recursive call; a block that
  * calls no recursion runs a bounded number of operations and never reads it.
  */
trait NarrowBlockProgram:

  /** The generated class's method: the natural, or null when stopped. Null is
    * the generated bytecode's "no value", made only by the stop's read and
    * returned through every generated call (`NarrowBlockCompilation`'s
    * `stopPolled` and `generatedCalled`); no Scala source writes or reads it
    * but `run`, the one boundary.
    */
  def computed(stop: StopSignal): BigInteger

  /** The natural, or nothing when `stop` asked for a stop. */
  final def run(stop: StopSignal): Option[BigInteger] = Option(computed(stop))

/** The narrow blocks of a program, compiled to JVM bytecode: every closed
  * narrow natural of the program (`NarrowKind.Value`) is one method of one
  * hidden class, every closed function and recursion's body the program calls
  * one static method over `java.math.BigInteger`, a constructor of the binary
  * naturals one operation of `BigInteger`, a call of one of the entry's natives
  * (`natives`) an `invokestatic` of its implementation's `StaticBlockMethod`,
  * and a branch on a natural a test of its sign and its low bit. A closed term
  * an operand decodes, a literal, is decoded once at compile time and loaded
  * from the class's data. The output is JVM bytecode.
  *
  * A filter `e ∥ binary_set true` compiles to nothing: every natural the block
  * makes is canonical, a native's result or a decoded literal. A literal
  * filtered by `binary_set false` is decoded only when it is positive. A block
  * that reads another filter, a native whose implementation is no
  * `StaticBlockMethod` of as many places, each of the canonical naturals, or a
  * literal that does not decode is not compiled.
  *
  * The class is built with `java.lang.classfile`'s builders, a local mutable
  * exception (`CONTRIBUTING.md`, "The code is 100% immutable"): they are used
  * only inside `compiled`, and nothing they build is kept but the class's
  * instance.
  */
/** A thunk of a program and the narrow check's reasons for refusing its body,
  * read as a recursion's body and as a closure's; nothing where it is narrow
  * (`NarrowBlockCompilation.thunkReadings`).
  */
final case class ThunkReading[C <: NativeSpecializer & Singleton](
    thunk: Configured[C],
    asRecursion: Option[String],
    asClosure: Option[String]
)

final case class NarrowBlockCompilation[C <: NativeSpecializer & Singleton](
    index: StandardLibraryIndex[C],
    natives: NativeBackend,
    // The configuration of the programs whose blocks it finds, under which a thunk is read for the identity.
    configuration: com.yang_bo.gezi.weakhead.ReadingConfiguration[C]
):

  private given C = configuration.specializer

  private val names: Map[Configured[C], NarrowKind] =
    val backendNames =
      NarrowBlockExtractor.boundTerms(index) ++ index.combinatorProperties.map(
        fact => Configured.fromPure(configuration.specializer)(fact.instruction)
      )
    // TODO (https://github.com/Atry/private-overlay/issues/1517):
    // the backend's names become the round's `leaves`.
    (index.noinline ++ backendNames + Configured.fromPure(
      configuration.specializer
    )(NarrowBlocks.fixpointByValue))
      .map(name =>
        name -> NarrowBlocks.nameKind(name, index, natives, configuration)
      )
      .toMap

  /** The static method a block calls for the entry's native of that name on
    * that many operands: its implementation when that is a `StaticBlockMethod`
    * of as many places, each of which declares the block's naturals, all this
    * block knows of an operand, with a result the block can hold
    * (`StaticBlockMethod.resultHeld`); none otherwise, and then a block that
    * calls the native is not compiled.
    */
  def staticMethod(name: NativeName, operands: Int): Option[StaticBlockMethod] =
    natives.natives
      .get(name)
      .filter(native =>
        native.parameters.size == operands && native.parameters
          .forall(_ == NativePlace.Fixed(StaticBlockMethod.blockNatural))
      )
      .flatMap(native =>
        native.implementation match
          case method: StaticBlockMethod
              if StaticBlockMethod.resultHeld(native, method) =>
            Some(method)
          case _ => None
      )

  /** The narrow kind of every subterm of the roots, a name's its own. */
  def kinds(roots: Vector[Configured[C]]): Map[Configured[C], NarrowKind] =
    @scala.annotation.tailrec
    def visited(
        pending: List[(Configured[C], Boolean)],
        found: Map[Configured[C], NarrowKind]
    ): Map[Configured[C], NarrowKind] =
      pending match
        case Nil                                                     => found
        case (instruction, _) :: rest if found.contains(instruction) =>
          visited(rest, found)
        case (instruction, _) :: rest if names.contains(instruction) =>
          visited(rest, found.updated(instruction, names(instruction)))
        case (instruction, _) :: rest if instruction.heldAsLeaf =>
          visited(rest, found.updated(instruction, NarrowKind.Closed))
        case (instruction, false) :: rest =>
          visited(
            parts(instruction).toList
              .map((_, false)) ::: (instruction, true) :: rest,
            found
          )
        case (instruction, true) :: rest =>
          val kind = instruction.layer match
            case Apply(function, argument) =>
              NarrowBlocks.applicationKind(found(function), found(argument))
            case Parallel(left, right) =>
              NarrowBlocks.parallelKind(found(left), found(right))
            case Choice(left, right) =>
              NarrowBlocks.choiceKind(Vector(found(left), found(right)))
            case Thunk(code, holes, fillings) =>
              NarrowBlocks.thunkKind(
                code,
                holes,
                fillings.map(filling =>
                  NarrowItem.Known(found(filling), filling)
                )
              ) match
                case NarrowKind.Closed
                    if NarrowBlocks.readsAsIdentity(
                      instruction,
                      configuration
                    ) =>
                  NarrowKind.Identity
                case kind => kind
            // A storage no narrow kind is read of: its terms were walked (`parts`), its view is not read.
            case UriNode(_) | Opaque(_) | _: com.yang_bo.gezi.ir.NativeStorage =>
              NarrowKind.Closed
          visited(rest, found.updated(instruction, kind))
    visited(roots.toList.map((_, false)), Map.empty)

  /** The terms one layer under the instruction: a storage's, the terms it holds
    * (`StorageHeldTerms`), its view not read and no storage walked below them
    * but through the terms it holds; any other's, its layer's children.
    */
  private def parts(instruction: Configured[C]): Vector[Configured[C]] =
    if com.yang_bo.gezi.ir.NativeStorage.stored(instruction.representation) then
      StorageHeldTerms.of(instruction)
    else instruction.layer.children

  /** Every thunk of the program with the narrow check's verdict on its body, in
    * the order of a walk from the root, each thunk once: read as a recursion's
    * body (the self call allowed) and as a closure's, each the reason of the
    * first code no production reads (`NarrowBlocks.explained`), or nothing when
    * the body is narrow. A diagnostic for whoever writes knowledge: why a typed
    * loop of an extraction stays out of a block. No decision of the framework
    * reads it.
    */
  def thunkReadings(program: Configured[C]): Vector[ThunkReading[C]] =
    val found = kinds(Vector(program))
    @scala.annotation.tailrec
    def walked(
        pending: List[Configured[C]],
        seen: Set[Configured[C]],
        made: Vector[ThunkReading[C]]
    ): Vector[ThunkReading[C]] =
      pending match
        case Nil => made
        case instruction :: rest
            if seen(instruction) || instruction.heldAsLeaf || names.contains(
              instruction
            ) =>
          walked(rest, seen + instruction, made)
        case instruction :: rest =>
          val reading = instruction.layer match
            case Thunk(code, holes, fillings) =>
              val items = fillings.map(filling =>
                NarrowItem.Known(
                  found.getOrElse(filling, NarrowKind.Closed),
                  filling
                )
              )
              Vector(
                ThunkReading(
                  instruction,
                  NarrowBlocks
                    .explained(code, holes, items, recursion = true)
                    .left
                    .toOption,
                  NarrowBlocks
                    .explained(code, holes, items, recursion = false)
                    .left
                    .toOption
                )
              )
            case _ => Vector.empty
          walked(
            instruction.layer.children.toList ::: rest,
            seen + instruction,
            made ++ reading
          )
    walked(List(program), Set.empty, Vector.empty)

  /** The maximal closed narrow naturals of the program, in the order of a walk
    * from its root, a subterm before those under it.
    */
  def blocks(program: Configured[C]): Vector[Configured[C]] =
    locatedBlocks(program, SourceMap.unlocated).map(_._1)

  /** The blocks of the program (`blocks`) with the map of each one's
    * occurrence, the map walked beside the program by `Layer.children`: the
    * place of a block met twice is its first occurrence's, and a place the map
    * leaves bare has its subterms unlocated. Throws `IllegalArgumentException`
    * for a map of another shape than the program where it locates anything
    * below a place.
    */
  def locatedBlocks(
      program: Configured[C],
      map: SourceMap
  ): Vector[(Configured[C], SourceMap)] =
    val found = kinds(Vector(program))
    @scala.annotation.tailrec
    def walked(
        pending: List[(Configured[C], SourceMap)],
        seen: Set[Configured[C]],
        made: Vector[(Configured[C], SourceMap)]
    ): Vector[(Configured[C], SourceMap)] =
      pending match
        case Nil                                           => made
        case (instruction, _) :: rest if seen(instruction) =>
          walked(rest, seen, made)
        case (instruction, placed) :: rest
            if found.get(instruction).contains(NarrowKind.Value) =>
          walked(rest, seen + instruction, made :+ (instruction, placed))
        case (instruction, _) :: rest
            if instruction.heldAsLeaf || names.contains(instruction) =>
          walked(rest, seen + instruction, made)
        case (instruction, placed) :: rest =>
          val children = instruction.layer.children
          require(
            placed.children.isEmpty || placed.children.size == children.size,
            s"a map of ${placed.children.size} places below ${children.size} subterms"
          )
          val childMaps = if placed.children.isEmpty then
            Vector.fill(children.size)(SourceMap.unlocated)
          else placed.children
          walked(
            children.zip(childMaps).toList ::: rest,
            seen + instruction,
            made
          )
    walked(List((program, map)), Set.empty, Vector.empty)

  /** The blocks compiled into one class, one method each, when every block
    * compiles, with the debugging attributes asked for; otherwise why not.
    */
  def compiled(
      blockRoots: Vector[Configured[C]],
      debug: DebugAttributes,
      stop: StopSignal
  ): Either[String, Vector[NarrowBlockProgram]] =
    generation(blockRoots, debug, stop).flatMap(_.defined())

  /** The class file of the blocks, as `compiled` defines it; otherwise why not.
    * What a reader of the class, a debugger or a test, reads of it.
    */
  def classFile(
      blockRoots: Vector[Configured[C]],
      debug: DebugAttributes,
      stop: StopSignal
  ): Either[String, scala.collection.immutable.ArraySeq[Byte]] =
    generation(blockRoots, debug, stop)
      .flatMap(_.classFile())
      .map(bytes => scala.collection.immutable.ArraySeq.unsafeWrapArray(bytes))

  /** The class's generation, when every block reads; the reading folds its
    * constants until the stop is asked for (`Reader`).
    */
  private def generation(
      blockRoots: Vector[Configured[C]],
      debug: DebugAttributes,
      stop: StopSignal
  ): Either[String, Generation] =
    val found = kinds(blockRoots)
    val reader = Reader(found, stop)
    val roots = blockRoots.map(reader.closed)
    for
      expressions <- Either.cond(
        roots.forall(_.isDefined),
        roots.flatten,
        s"a block does not read: ${blockRoots.zip(roots).collectFirst {
            case (root, None) => root
          }}"
      )
      functions <- reader.functionsOf(expressions)
    yield Generation(
      found,
      reader,
      expressions,
      functions,
      DebugAttributes.lines(debug, blockRoots.size)
    )

  /** The reading of closed terms into expressions, by their kinds. A native
    * applied to operands that read as literals or folded naturals is folded
    * (`folded`), until the stop is asked for: from then on nothing is folded,
    * so that a costly constant cannot hold a compilation that is asked to stop,
    * and the expression is emitted as read, which computes the same.
    */
  private final case class Reader(
      found: Map[Configured[C], NarrowKind],
      stop: StopSignal
  ):

    private def kind(instruction: Configured[C]): NarrowKind =
      found.getOrElse(instruction, NarrowKind.Closed)

    /** The term with the member of each outer choice that the backend compiles
      * chosen (`NarrowBlocks.chosenMember`), among the members of the choice's
      * whole right `+` spine, a right side that is a name ending it.
      */
    @scala.annotation.tailrec
    private def chosen(instruction: Configured[C]): Configured[C] =
      if names.contains(instruction) || instruction.heldAsLeaf then instruction
      else
        instruction.layer match
          case Choice(_, _) =>
            val members = com.yang_bo.gezi.ir.ChoiceSpine.members[Configured[C]](
              instruction,
              current =>
                if !Configured.same(current, instruction) && names.contains(
                    current
                  )
                then None
                else
                  current.layer match
                    case Choice(left, right) => Some((left, right))
                    case _                   => None
            )
            NarrowBlocks.chosenMember(members.map(kind)) match
              case Some(position) => chosen(members(position))
              case None           => instruction
          case _ => instruction

    /** The head of the term's application spine and its arguments, the
      * innermost application's argument first, each function position's choice
      * resolved (`chosen`). Stack-safe: a loop down the function positions, the
      * arguments gathered on the way.
      */
    private def spine(
        instruction: Configured[C]
    ): (Configured[C], Vector[Configured[C]]) =
      @scala.annotation.tailrec
      def unwound(
          current: Configured[C],
          outerArguments: List[Configured[C]]
      ): (Configured[C], Vector[Configured[C]]) =
        val resolved = chosen(current)
        if names.contains(resolved) || resolved.heldAsLeaf then
          (resolved, outerArguments.toVector)
        else
          resolved.layer match
            case Apply(function, argument) =>
              unwound(function, argument :: outerArguments)
            case _ => (resolved, outerArguments.toVector)
      unwound(instruction, Nil)

    /** The expression of a closed narrow natural. Stack-safe: read on
      * `scala.util.control.TailCalls`, so a natural nested as deep as a
      * program's term is read without a JVM frame per level.
      */
    def closed(
        instruction: Configured[C]
    ): Option[NarrowExpression[Configured[C]]] =
      closedReading(instruction).result

    private def closedReading(
        instruction: Configured[C]
    ): TailRec[Option[NarrowExpression[Configured[C]]]] =
      val resolved = chosen(instruction)
      if names.contains(resolved) || resolved.heldAsLeaf then done(None)
      else
        resolved.layer match
          case Parallel(value, criterion) =>
            kind(criterion) match
              case NarrowKind.Criterion(true)  => tailcall(operand(value))
              case NarrowKind.Criterion(false) =>
                done(Some(NarrowExpression.Literal(resolved)))
              case _ => done(None)
          case Apply(_, _) =>
            val (head, arguments) = spine(resolved)
            kind(head) match
              case NarrowKind.Native(name, places, 0)
                  if arguments.size == places =>
                tailcall(operands(arguments)).map(
                  _.map(read => folded(resolved, name, read))
                )
              case NarrowKind.Fixpoint =>
                arguments.headOption match
                  case Some(body) =>
                    kind(body) match
                      case NarrowKind.Thunk(_, true, holes)
                          if arguments.size == holes =>
                        tailcall(operands(arguments.tail))
                          .map(_.map(NarrowExpression.RecursionCall(body, _)))
                      case _ => done(None)
                  case None => done(None)
              case NarrowKind.Thunk(true, _, holes)
                  if arguments.size == holes =>
                tailcall(operands(arguments)).map(
                  _.map(NarrowExpression.Call(head, _))
                )
              case _ => done(None)
          case _ => done(None)

    private def operand(
        instruction: Configured[C]
    ): TailRec[Option[NarrowExpression[Configured[C]]]] =
      kind(instruction) match
        case NarrowKind.Closed | NarrowKind.Native(_, 0, 0) =>
          done(Some(NarrowExpression.Literal(instruction)))
        case _ => tailcall(closedReading(instruction))

    /** The native's call on the operands read, folded into the natural it
      * computes when every operand's value is known (`valueOf`) and the
      * native's value on them is (`computed`), and the stop is not asked for;
      * otherwise the call. A fold reads the values of its operands only, each a
      * literal decoded or a natural folded already, so reading a natural folds
      * it in one pass, bottom up.
      */
    private def folded(
        closed: Configured[C],
        name: NativeName,
        read: Vector[NarrowExpression[Configured[C]]]
    ): NarrowExpression[Configured[C]] =
      val call = NarrowExpression.Native(name, read)
      if stop.stopRequested then call
      else
        val values = read.map(valueOf)
        if values.forall(_.isDefined) then
          computed(name, values.flatten).fold(call)(
            NarrowExpression.Folded(closed, _)
          )
        else call

    /** The value of an operand read: a folded natural's, a literal's decoded
      * (`decoded`); none otherwise.
      */
    private def valueOf(read: NarrowExpression[Configured[C]]): Option[BigInt] =
      read match
        case NarrowExpression.Folded(_, value) => Some(value)
        case NarrowExpression.Literal(literal) => decoded(literal)
        case _                                 => None

    /** Each instruction read as an operand, in order; nothing at the first that
      * does not read, which is the same as reading them all, reading being
      * pure.
      */
    private def operands(
        instructions: Vector[Configured[C]]
    ): TailRec[Option[Vector[NarrowExpression[Configured[C]]]]] =
      NarrowBlockCompilation.allRead(instructions)(operand)

    /** The body of a closed function, or of a recursion's when `recursion`. */
    def body(
        function: Configured[C],
        recursion: Boolean
    ): Option[NarrowExpression[Configured[C]]] =
      function.layer match
        case Thunk(code, holes, fillings) =>
          NarrowBlocks
            .body(
              code,
              holes,
              fillings.map(filling => NarrowItem.Known(kind(filling), filling)),
              recursion
            )
            .flatMap(fullCalls)
        case _ => None

    /** The expression with each call of a partial application
      * (`NarrowExpression.PartialApplication`) read as the full call of its
      * head: a native's call, or a recursion's call when the head is the fixed
      * point combinator, whose first operand is the recursion's body. The
      * partial application's own operands, each read as an operand, come before
      * the call's; none when one of them does not read. Every other part is
      * kept, read in turn. Stack-safe: read on `scala.util.control.TailCalls`.
      */
    private def fullCalls(
        expression: NarrowExpression[Configured[C]]
    ): Option[NarrowExpression[Configured[C]]] =
      fullCallsReading(expression).result

    private def fullCallsReading(
        expression: NarrowExpression[Configured[C]]
    ): TailRec[Option[NarrowExpression[Configured[C]]]] =
      def all(
          expressions: Vector[NarrowExpression[Configured[C]]]
      ): TailRec[Option[Vector[NarrowExpression[Configured[C]]]]] =
        NarrowBlockCompilation.allRead(expressions)(part =>
          tailcall(fullCallsReading(part))
        )
      def withRest(
          suppliedOperands: Option[Vector[NarrowExpression[Configured[C]]]],
          arguments: Vector[NarrowExpression[Configured[C]]]
      )(
          made: Vector[NarrowExpression[Configured[C]]] => NarrowExpression[
            Configured[C]
          ]
      ): TailRec[Option[NarrowExpression[Configured[C]]]] =
        suppliedOperands match
          case None       => done(None)
          case Some(read) =>
            all(arguments).map(_.map(rest => made(read ++ rest)))
      expression match
        case NarrowExpression.PartialApplication(partial, arguments) =>
          val (head, supplied) = spine(chosen(partial))
          (kind(head), supplied) match
            case (NarrowKind.Native(name, _, 0), _) =>
              tailcall(operands(supplied)).flatMap(
                withRest(_, arguments)(NarrowExpression.Native(name, _))
              )
            case (NarrowKind.Fixpoint, body +: suppliedParameters) =>
              tailcall(operands(suppliedParameters)).flatMap(
                withRest(_, arguments)(NarrowExpression.RecursionCall(body, _))
              )
            case _ => done(None)
        case NarrowExpression.Native(name, arguments) =>
          all(arguments).map(_.map(NarrowExpression.Native(name, _)))
        case NarrowExpression.Call(function, arguments) =>
          all(arguments).map(_.map(NarrowExpression.Call(function, _)))
        case NarrowExpression.SelfCall(arguments) =>
          all(arguments).map(_.map(NarrowExpression.SelfCall(_)))
        case NarrowExpression.RecursionCall(body, arguments) =>
          all(arguments).map(_.map(NarrowExpression.RecursionCall(body, _)))
        case NarrowExpression.Branch(
              scrutinee,
              zero,
              evenHalf,
              even,
              oddHalf,
              odd
            ) =>
          all(Vector(scrutinee, zero, even, odd)).map(_.map {
            case Vector(readScrutinee, readZero, readEven, readOdd) =>
              NarrowExpression.Branch(
                readScrutinee,
                readZero,
                evenHalf,
                readEven,
                oddHalf,
                readOdd
              )
            case other =>
              throw IllegalStateException(
                s"four parts of a branch, not ${other.size}"
              )
          })
        case NarrowExpression.Let(binder, value, body) =>
          tailcall(fullCallsReading(value)).flatMap {
            case None            => done(None)
            case Some(readValue) =>
              tailcall(fullCallsReading(body)).map(
                _.map(NarrowExpression.Let(binder, readValue, _))
              )
          }
        case other => done(Some(other))

    /** Every function and recursion's body the expressions call, with its body,
      * closed under the calls of those bodies; nothing when one does not read.
      */
    def functionsOf(
        expressions: Vector[NarrowExpression[Configured[C]]]
    ): Either[String, Vector[
      (Configured[C], Boolean, NarrowExpression[Configured[C]])
    ]] =
      @scala.annotation.tailrec
      def closedOver(
          pending: List[(Configured[C], Boolean)],
          made: Vector[
            (Configured[C], Boolean, NarrowExpression[Configured[C]])
          ]
      ): Either[String, Vector[
        (Configured[C], Boolean, NarrowExpression[Configured[C]])
      ]] =
        pending match
          case Nil => Right(made)
          case (function, recursion) :: rest
              if made.exists((other, otherRecursion, _) =>
                Configured.same(other, function) && otherRecursion == recursion
              ) =>
            closedOver(rest, made)
          case (function, recursion) :: rest =>
            body(function, recursion) match
              case None =>
                Left(
                  s"a function's body does not read (recursion $recursion): $function"
                )
              case Some(read) =>
                closedOver(
                  calls(read).toList ::: rest,
                  made :+ (function, recursion, read)
                )
      closedOver(expressions.flatMap(calls).toList, Vector.empty)

    /** The functions and recursions' bodies an expression calls, closed
      * naturals inside it read in turn: in preorder, a call before the calls in
      * its operands, the parts left to right. Stack-safe: a loop over the parts
      * still to walk.
      */
    def calls(
        expression: NarrowExpression[Configured[C]]
    ): Vector[(Configured[C], Boolean)] =
      @scala.annotation.tailrec
      def walked(
          pending: List[NarrowExpression[Configured[C]]],
          made: Vector[(Configured[C], Boolean)]
      ): Vector[(Configured[C], Boolean)] =
        pending match
          case Nil          => made
          case next :: rest =>
            next match
              case NarrowExpression.Literal(_) | NarrowExpression.Folded(_, _) |
                  NarrowExpression.ClosedCode(_, _) =>
                walked(rest, made)
              case NarrowExpression.Value(closedValue) =>
                walked(closed(closedValue).toList ::: rest, made)
              case NarrowExpression.Variable(_)          => walked(rest, made)
              case NarrowExpression.Native(_, arguments) =>
                walked(arguments.toList ::: rest, made)
              case NarrowExpression.PartialApplication(partial, _) =>
                throw IllegalStateException(
                  s"a partial application the reader did not expand: $partial"
                )
              case NarrowExpression.Call(function, arguments) =>
                walked(arguments.toList ::: rest, made :+ (function, false))
              case NarrowExpression.SelfCall(arguments) =>
                walked(arguments.toList ::: rest, made)
              case NarrowExpression.RecursionCall(body, arguments) =>
                walked(arguments.toList ::: rest, made :+ (body, true))
              case NarrowExpression.Branch(scrutinee, zero, _, even, _, odd) =>
                walked(scrutinee :: zero :: even :: odd :: rest, made)
              case NarrowExpression.Let(_, value, body) =>
                walked(value :: body :: rest, made)
      walked(List(expression), Vector.empty)

  /** A literal decoded at compile time: a canonical binary natural built of the
    * constructors' natives, each under its filters, or under the contract
    * `arrow D R C` (native_types', read by its term), a filter or a contract's
    * domain and range read at their parameters, an application of the identity
    * read as its argument; nothing for any other term. A noinline name's
    * instruction is its own layer (hash consing), read the same way.
    */
  private def decoded(instruction: Configured[C]): Option[BigInt] =
    names.get(instruction) match
      case Some(NarrowKind.Native(BinaryNaturalFamily.zeroNative, 0, 0)) =>
        Some(BigInt(0))
      case _ if instruction.heldAsLeaf => None
      case _                           =>
        instruction.layer match
          case Parallel(value, criterion) =>
            decoded(value).filter(admitted(criterion, _))
          case Apply(function, argument) =>
            kinds(Vector(function)).get(function) match
              case Some(NarrowKind.Identity) => decoded(argument)
              case _                         =>
                decoded(argument).flatMap(field =>
                  constructed(function, field).orElse(
                    contracted(function).flatMap((domain, range, constructor) =>
                      if admitted(domain, field) then
                        constructed(constructor, field).filter(
                          admitted(range, _)
                        )
                      else None
                    )
                  )
                )
          case _ => None

  /** The value of a native's call on the values given, computed at compile time
    * as the block would compute it: the binary naturals' constructors as
    * `constructed` reads a canonical natural (so that no fold makes the
    * non-canonical `even zero`, which is then left to the code), and any other
    * native by its static method (`staticMethod`), invoked as the block's
    * `invokestatic` would invoke it; none for a native of neither.
    */
  private def computed(
      name: NativeName,
      values: Vector[BigInt]
  ): Option[BigInt] =
    (name, values) match
      case (BinaryNaturalFamily.zeroNative, Vector())      => Some(BigInt(0))
      case (BinaryNaturalFamily.evenNative, Vector(field)) =>
        Option.when(field > 0)(field * 2)
      case (BinaryNaturalFamily.oddNative, Vector(field)) => Some(field * 2 + 1)
      case _                                              =>
        staticMethod(name, values.size).map(method =>
          val handle = MethodHandles
            .publicLookup()
            .findStatic(
              Class.forName(method.className, true, getClass.getClassLoader),
              method.methodName,
              java.lang.invoke.MethodType.methodType(
                classOf[BigInteger],
                java.util.Collections.nCopies(values.size, classOf[BigInteger])
              )
            )
          handle.invokeWithArguments(
            java.util.List.of(values.map(_.bigInteger)*)
          ) match
            case result: BigInteger => BigInt(result)
            case other              =>
              throw IllegalStateException(
                s"the static method of $name returned no natural: $other"
              )
        )

  /** The natural a constructor's native makes of its field. */
  private def constructed(
      constructor: Configured[C],
      field: BigInt
  ): Option[BigInt] =
    names.get(constructor) match
      case Some(NarrowKind.Native(BinaryNaturalFamily.evenNative, 1, 0))
          if field > 0 =>
        Some(field * 2)
      case Some(NarrowKind.Native(BinaryNaturalFamily.oddNative, 1, 0)) =>
        Some(field * 2 + 1)
      case _ => None

  /** Whether the criterion `binary_set p` admits the canonical natural. */
  private def admitted(criterion: Configured[C], number: BigInt): Boolean =
    kinds(Vector(criterion)).get(criterion) match
      case Some(NarrowKind.Criterion(admitsZero)) => admitsZero || number > 0
      case _                                      => false

  /** The domain, the range and the function of a term `arrow D R C`, the
    * contract read by its term under applications of the identity.
    */
  private def contracted(
      term: Configured[C]
  ): Option[(Configured[C], Configured[C], Configured[C])] =
    if term.heldAsLeaf then None
    else
      term.layer match
        case Apply(partial, function) =>
          partial.layer match
            case Apply(head, range) =>
              head.layer match
                case Apply(contractTerm, domain)
                    if Configured.same(
                      withoutIdentity(contractTerm),
                      Configured.fromPure(configuration.specializer)(
                        NarrowBlockCompilation.contract
                      )
                    ) =>
                  Some((domain, range, function))
                case _ => None
            case _ => None
        case _ => None

  /** The term with every application of the identity at its root taken off. */
  @scala.annotation.tailrec
  private def withoutIdentity(term: Configured[C]): Configured[C] =
    if term.heldAsLeaf then term
    else
      term.layer match
        case Apply(function, argument)
            if kinds(Vector(function))
              .get(function)
              .contains(NarrowKind.Identity) =>
          withoutIdentity(argument)
        case _ => term

  /** The class of the blocks and the functions they call. */
  private final case class Generation(
      found: Map[Configured[C], NarrowKind],
      reader: Reader,
      blocks: Vector[NarrowExpression[Configured[C]]],
      functions: Vector[
        (Configured[C], Boolean, NarrowExpression[Configured[C]])
      ],
      lines: Option[ClassLines]
  ):

    private val bigInteger = ClassDesc.of("java.math.BigInteger")
    private val generatedClass =
      ClassDesc.of("com.yang_bo.gezi.narrowblocks.GeneratedNarrowBlock")
    private val programInterface =
      ClassDesc.of("com.yang_bo.gezi.narrowblocks.NarrowBlockProgram")
    private val stopSignal = ClassDesc.of("com.yang_bo.gezi.saturation.StopSignal")
    private val objectClass = ConstantDescs.CD_Object

    /** The type of a native's static method: its operands to its natural. */
    private def nativeMethodType(parameters: Int): MethodTypeDesc =
      MethodTypeDesc.of(bigInteger, Vector.fill(parameters)(bigInteger)*)

    /** The type of a generated block's or function's static method: its
      * operands, then the stop signal, in the slot after them, to its natural
      * or null. The stop comes last so that a call pushes it after its
      * arguments' code has run (`generatedCalled`): pushed first, a chain of
      * calls n deep held n stops on the operand stack, and each branch's frame
      * of the stack map listed them all, so that the class's stack map grew as
      * the square of the depth, and at 3,000 to 4,000 calls deep the JVM failed
      * with an internal error in its metaspace defining the class
      * (`metaspaceArena.cpp:85`, measured 2026-11-19).
      */
    private def generatedMethodType(parameters: Int): MethodTypeDesc =
      MethodTypeDesc.of(
        bigInteger,
        (Vector.fill(parameters)(bigInteger) :+ stopSignal)*
      )

    private val functionNumbers: Map[(Configured[C], Boolean), Int] =
      functions.zipWithIndex.map { case ((function, recursion, _), number) =>
        ((function, recursion), number)
      }.toMap

    private def parameterCount(
        function: Configured[C],
        recursion: Boolean
    ): Int = function.layer match
      case Thunk(_, holes, _) =>
        if recursion then holes.size - 1 else holes.size
      case other =>
        throw IllegalStateException(s"a function is a thunk, not $other")

    /** Every literal the blocks and the functions read, with its value, in the
      * order first met: a folded natural's computed, another literal's decoded;
      * nothing when one does not decode.
      */
    private val literals: Option[Vector[(Configured[C], BigInt)]] =
      val all =
        (blocks ++ functions.map(_._3)).flatMap(literalsOf).distinctBy(_._1)
      val read = all.map((literal, value) =>
        value.orElse(decoded(literal)).map((literal, _))
      )
      Option.when(read.forall(_.isDefined))(read.flatten)

    /** The literals of the expression, in preorder, the parts left to right, a
      * closed natural read in place. Stack-safe: a loop over the parts still to
      * walk.
      */
    private def literalsOf(
        expression: NarrowExpression[Configured[C]]
    ): Vector[(Configured[C], Option[BigInt])] =
      @scala.annotation.tailrec
      def walked(
          pending: List[NarrowExpression[Configured[C]]],
          made: Vector[(Configured[C], Option[BigInt])]
      ): Vector[(Configured[C], Option[BigInt])] =
        pending match
          case Nil          => made
          case next :: rest =>
            next match
              case NarrowExpression.Literal(literal) =>
                walked(rest, made :+ (literal, None))
              case NarrowExpression.Folded(literal, value) =>
                walked(rest, made :+ (literal, Some(value)))
              case NarrowExpression.ClosedCode(code, environment) =>
                walked(
                  rest,
                  made :+ (
                    NarrowBlockCompilation.instantiated(code, environment),
                    None
                  )
                )
              case NarrowExpression.Value(closedValue) =>
                walked(reader.closed(closedValue).toList ::: rest, made)
              case NarrowExpression.Variable(_)          => walked(rest, made)
              case NarrowExpression.Native(_, arguments) =>
                walked(arguments.toList ::: rest, made)
              case NarrowExpression.PartialApplication(partial, _) =>
                throw IllegalStateException(
                  s"a partial application the reader did not expand: $partial"
                )
              case NarrowExpression.Call(_, arguments) =>
                walked(arguments.toList ::: rest, made)
              case NarrowExpression.SelfCall(arguments) =>
                walked(arguments.toList ::: rest, made)
              case NarrowExpression.RecursionCall(_, arguments) =>
                walked(arguments.toList ::: rest, made)
              case NarrowExpression.Branch(scrutinee, zero, _, even, _, odd) =>
                walked(scrutinee :: zero :: even :: odd :: rest, made)
              case NarrowExpression.Let(_, value, body) =>
                walked(value :: body :: rest, made)
      walked(List(expression), Vector.empty)

    /** Why the expressions cannot be emitted, the first reason in reading order
      * (preorder, the parts left to right, a closed natural read in place): a
      * native call that is neither a constructor of the binary naturals nor a
      * `StaticBlockMethod` of as many places, or a closed natural that does not
      * read; none when every part can be emitted. Stack-safe: a loop over the
      * parts still to walk.
      */
    private def firstUnsupported(
        expressions: Vector[NarrowExpression[Configured[C]]]
    ): Option[String] =
      @scala.annotation.tailrec
      def walked(
          pending: List[NarrowExpression[Configured[C]]]
      ): Option[String] =
        pending match
          case Nil          => None
          case next :: rest =>
            next match
              case NarrowExpression.Native(name, arguments) =>
                if NarrowBlockCompilation.operations.contains(
                    (name, arguments.size)
                  ) || staticMethod(name, arguments.size).isDefined
                then walked(arguments.toList ::: rest)
                else
                  Some(
                    s"the native $name of ${arguments.size} operands has no static method a block can call"
                  )
              case NarrowExpression.Value(closedValue) =>
                reader.closed(closedValue) match
                  case Some(read) => walked(read :: rest)
                  case None       =>
                    Some(s"a closed natural does not read: $closedValue")
              case NarrowExpression.Call(_, arguments) =>
                walked(arguments.toList ::: rest)
              case NarrowExpression.PartialApplication(partial, _) =>
                throw IllegalStateException(
                  s"a partial application the reader did not expand: $partial"
                )
              case NarrowExpression.SelfCall(arguments) =>
                walked(arguments.toList ::: rest)
              case NarrowExpression.RecursionCall(_, arguments) =>
                walked(arguments.toList ::: rest)
              case NarrowExpression.Branch(scrutinee, zero, _, even, _, odd) =>
                walked(scrutinee :: zero :: even :: odd :: rest)
              case NarrowExpression.Let(_, value, body) =>
                walked(value :: body :: rest)
              case NarrowExpression.Literal(_) | NarrowExpression.Folded(_, _) |
                  NarrowExpression.ClosedCode(_, _) |
                  NarrowExpression.Variable(_) =>
                walked(rest)
      walked(expressions.toList)

    /** The class defined and its instances, one for each block; none, with the
      * reason, when a literal does not decode, a part cannot be emitted
      * (`firstUnsupported`), or a method could exceed the JVM's limit on a
      * method's code (`oversized`).
      */
    def defined(): Either[String, Vector[NarrowBlockProgram]] =
      checked.map { decodedLiterals =>
        val constants: Vector[AnyRef] =
          decodedLiterals.map((_, number) => number.bigInteger)
        val lookup = MethodHandles.lookup()
        val hidden = lookup.defineHiddenClassWithClassData(
          bytes(decodedLiterals),
          java.util.List.of(constants*),
          true
        )
        val constructor =
          hidden.lookupClass().getDeclaredConstructor(classOf[Int])
        blocks.indices.toVector.map(number =>
          constructor.newInstance(Integer.valueOf(number)) match
            case program: NarrowBlockProgram => program
            case other                       =>
              throw IllegalStateException(
                s"the generated class is no narrow block: $other"
              )
        )
      }

    /** The class file `defined` defines; none, with the reason, as there. */
    def classFile(): Either[String, Array[Byte]] = checked.map(bytes)

    /** The literals decoded, when the class can be built. */
    private def checked: Either[String, Vector[(Configured[C], BigInt)]] =
      for
        decodedLiterals <- literals.toRight("a literal does not decode")
        _ <- firstUnsupported(blocks ++ functions.map(_._3)).toLeft(())
        _ <- oversized.toLeft(())
      yield decodedLiterals

    /** The class's bytes over the decoded literals, which its data holds in
      * that order: with the debugging attributes of `lines`, the `SourceFile`
      * and, for blocks from several files, the `SourceDebugExtension`, and a
      * line at the start of each block's method that has a place.
      */
    private def bytes(
        decodedLiterals: Vector[(Configured[C], BigInt)]
    ): Array[Byte] =
      val literalIndex = decodedLiterals.map(_._1).zipWithIndex.toMap
      val resolver = ClassHierarchyResolver
        .defaultResolver()
        .orElse(ClassHierarchyResolver.ofClassLoading(getClass.getClassLoader))
      ClassFile
        .of(ClassFile.ClassHierarchyResolverOption.of(resolver))
        .build(
          generatedClass,
          (classBuilder: ClassBuilder) =>
            classBuilder
              .withFlags(ClassFile.ACC_PUBLIC | ClassFile.ACC_FINAL)
              .withInterfaceSymbols(programInterface)
            lines.foreach(found =>
              classBuilder.`with`(SourceFileAttribute.of(found.sourceFile))
              found.sourceMap.foreach(written =>
                classBuilder.`with`(
                  SourceDebugExtensionAttribute.of(
                    written.getBytes(java.nio.charset.StandardCharsets.UTF_8)
                  )
                )
              )
            )
            classBuilder.withField(
              "block",
              ConstantDescs.CD_int,
              ClassFile.ACC_PRIVATE | ClassFile.ACC_FINAL
            )
            classBuilder.withMethodBody(
              ConstantDescs.INIT_NAME,
              MethodTypeDesc.of(ConstantDescs.CD_void, ConstantDescs.CD_int),
              ClassFile.ACC_PUBLIC,
              (code: CodeBuilder) =>
                code
                  .aload(0)
                  .invokespecial(
                    objectClass,
                    ConstantDescs.INIT_NAME,
                    ConstantDescs.MTD_void
                  )
                  .aload(0)
                  .iload(1)
                  .putfield(generatedClass, "block", ConstantDescs.CD_int)
                  .return_()
                ()
            )
            classBuilder.withMethodBody(
              "computed",
              MethodTypeDesc.of(bigInteger, stopSignal),
              ClassFile.ACC_PUBLIC,
              (code: CodeBuilder) =>
                blocks.indices.foreach { number =>
                  val next = code.newLabel()
                  code
                    .aload(0)
                    .getfield(generatedClass, "block", ConstantDescs.CD_int)
                  code.loadConstant(Integer.valueOf(number))
                  code.if_icmpne(next)
                  code.aload(1)
                  code.invokestatic(
                    generatedClass,
                    s"block$number",
                    generatedMethodType(0)
                  )
                  code.areturn()
                  code.labelBinding(next)
                }
                code.aconst_null().areturn()
                ()
            )
            blocks.zipWithIndex.foreach { (expression, number) =>
              classBuilder.withMethodBody(
                s"block$number",
                generatedMethodType(0),
                ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC,
                (code: CodeBuilder) =>
                  lines
                    .flatMap(_.blockLines(number))
                    .foreach(line => code.lineNumber(line))
                  Emission(code, literalIndex, None, Map.empty, 1, 0)
                    .emitted(expression)
                  code.areturn()
                  ()
              )
            }
            functions.foreach { (function, recursion, body) =>
              val number = functionNumbers((function, recursion))
              val parameters = parameterCount(function, recursion)
              val firstParameter = if recursion then 1 else 0
              classBuilder.withMethodBody(
                s"function$number",
                generatedMethodType(parameters),
                ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC,
                (code: CodeBuilder) =>
                  if recursion then stopPolled(code, parameters)
                  val slots = (0 until parameters)
                    .map(position => (firstParameter + position, position))
                    .toMap
                  Emission(
                    code,
                    literalIndex,
                    Option.when(recursion)((number, parameters)),
                    slots,
                    1 + parameters,
                    parameters
                  )
                    .emitted(body)
                  code.areturn()
                  ()
              )
            }
        )

    /** Why a method of the class could exceed the JVM's limit on a method's
      * code, 65,535 bytes (`maximumCodeLength`), by the bounds of
      * `codeSizeBound`; none when every method is within it. A block is one
      * method, its expression emitted whole into it, so a closed natural nested
      * deeply enough would overflow it: measured 2026-11-17, a chain of native
      * plus over literals takes 5 to 21 bytes a level, and at depth 20,000 the
      * class build threw `IllegalArgumentException: Code length 100003 is
      * outside the allowed range`. Refused here, the block is left to the
      * general reading, as a block that does not read is.
      */
    private def oversized: Option[String] =
      val methods =
        blocks.zipWithIndex.map((expression, number) =>
          (s"block$number", codeSizeBound(expression) + methodOverheadBound)
        ) ++
          functions.map((function, recursion, body) =>
            (
              s"function${functionNumbers((function, recursion))}",
              codeSizeBound(body) + methodOverheadBound
            )
          ) :+ (
            "computed",
            blocks.size.toLong * dispatchBound + methodOverheadBound
          )
      methods.collectFirst {
        case (name, bound) if bound > maximumCodeLength =>
          s"the method $name may take up to $bound bytes of code, beyond the JVM's $maximumCodeLength"
      }

    /** An upper bound on the bytes of code `Emission` writes for the
      * expression: each part's instructions at their widest form (a constant
      * pool reference of three bytes, a local variable's load or store with its
      * `wide` prefix, a branch widened to `goto_w` as the class file writer
      * does when its offset does not fit), a closed natural read in place.
      * Stack-safe: a loop over the parts still to walk.
      */
    private def codeSizeBound(
        expression: NarrowExpression[Configured[C]]
    ): Long =
      @scala.annotation.tailrec
      def walked(
          pending: List[NarrowExpression[Configured[C]]],
          total: Long
      ): Long =
        pending match
          case Nil          => total
          case next :: rest =>
            next match
              case NarrowExpression.Literal(_) | NarrowExpression.Folded(_, _) |
                  NarrowExpression.ClosedCode(_, _) =>
                walked(rest, total + 3)
              case NarrowExpression.Value(closedValue) =>
                reader.closed(closedValue) match
                  case Some(read) => walked(read :: rest, total)
                  case None       =>
                    throw IllegalStateException(
                      s"a closed natural does not read: $closedValue"
                    )
              case NarrowExpression.Variable(_) => walked(rest, total + 4)
              case NarrowExpression.Native(name, arguments) =>
                val operation = NarrowBlockCompilation.operations
                  .get((name, arguments.size))
                  .fold(3)(_.codeSizeBound)
                walked(arguments.toList ::: rest, total + operation)
              case NarrowExpression.PartialApplication(partial, _) =>
                throw IllegalStateException(
                  s"a partial application the reader did not expand: $partial"
                )
              case NarrowExpression.Call(_, arguments) =>
                walked(arguments.toList ::: rest, total + callBound)
              case NarrowExpression.SelfCall(arguments) =>
                walked(arguments.toList ::: rest, total + callBound)
              case NarrowExpression.RecursionCall(_, arguments) =>
                walked(arguments.toList ::: rest, total + callBound)
              case NarrowExpression.Branch(scrutinee, zero, _, even, _, odd) =>
                walked(
                  scrutinee :: zero :: even :: odd :: rest,
                  total + branchBound
                )
              case NarrowExpression.Let(_, value, body) =>
                walked(value :: body :: rest, total + 4)
      walked(List(expression), 0)

    /** The JVM's limit on a method's code, in bytes. */
    private val maximumCodeLength: Long = 65535

    /** A generated call (`generatedCalled`) besides its arguments: the stop's
      * `aload` with its `wide` prefix, `invokestatic`, `dup`, `ifnonnull`
      * widened to an inverted branch over a `goto_w`, `areturn`.
      */
    private val callBound: Long = 4 + 3 + 1 + 8 + 1

    /** A branch (`Emission.steps`' `Branch`) besides its parts: two stores and
      * four loads with `wide`, three `invokevirtual`s, two `iconst`s, two
      * `ifne`s widened to eight bytes and two `goto`s widened to `goto_w`.
      */
    private val branchBound: Long =
      2 * 4 + 4 * 4 + 3 * 3 + 2 * 1 + 2 * 8 + 2 * 5

    /** A method besides its expression: a recursion's poll (`stopPolled`, the
      * stop's `aload` with its `wide` prefix, `invokeinterface`, a widened
      * `ifeq`, `aconst_null`, `areturn`) and the closing `areturn`, rounded up.
      */
    private val methodOverheadBound: Long = 32

    /** One block's dispatch in `computed`: `aload_0`, `getfield`, its number
      * loaded, a widened `if_icmpne`, `aload_1`, `invokestatic`, `areturn`,
      * rounded up.
      */
    private val dispatchBound: Long = 32

    /** A recursion's poll, at its method's entry: return null, the bytecode's
      * "no value", when the stop signal in slot 0 asks for a stop. Null, not a
      * typed outcome: a generated method returns its natural as a BigInteger
      * reference, and a stop is one more value of that return; an outcome
      * object would cost an allocation on every recursive call's return, the
      * hot path of the block, to carry a stop that comes once. It stays in the
      * generated code: the one boundary that reads it is
      * `NarrowBlockProgram.run`, which gives an `Option`.
      */
    private def stopPolled(code: CodeBuilder, stopSlot: Int): Unit =
      val going = code.newLabel()
      code
        .aload(stopSlot)
        .invokeinterface(
          stopSignal,
          "stopRequested",
          MethodTypeDesc.of(ConstantDescs.CD_boolean)
        )
      code.ifeq(going)
      code.aconst_null().areturn()
      code.labelBinding(going)
      ()

    /** The call of a generated function, as emission steps: the arguments'
      * steps (`pushed`), then the stop signal of the calling method's slot
      * pushed, then the method invoked and a null it returns, a stop, returned
      * at once from the calling method.
      */
    private def generatedCalled(
        code: CodeBuilder,
        stopSlot: Int,
        method: String,
        arguments: Int
    )(
        pushed: List[EmissionStep]
    ): List[EmissionStep] =
      val going = code.newLabel()
      pushed ::: List(EmissionStep.emitting(() =>
        code.aload(stopSlot)
        code.invokestatic(
          generatedClass,
          method,
          generatedMethodType(arguments)
        )
        code.dup().ifnonnull(going)
        code.areturn()
        code.labelBinding(going)
        ()
      ))

    /** A step of a method's emission, taken by `taken`, which gives the steps
      * that come in its place: an expression still to emit under its emission
      * (`EmissionStep.expression`, in place of its steps), or bytecode to emit
      * on the code builder (`EmissionStep.emitting`, in place of nothing), such
      * as what comes after an expression's parts (a native's invoke after its
      * operands). A function rather than an enum of the two: a pattern match on
      * a case that holds an `Emission` makes Scala 3.10.0's pattern matcher
      * load the sealed `CodeBuilder`'s JDK subclasses and crash on a cyclic
      * reference (`BufferedMethodBuilder`).
      */
    private final case class EmissionStep(taken: () => List[EmissionStep])

    private object EmissionStep:

      /** The expression emitted under the emission. */
      def expression(
          expression: NarrowExpression[Configured[C]],
          emission: Emission
      )(using C): EmissionStep =
        EmissionStep(() => emission.steps(expression))

      /** The bytecode `emitted` emits. */
      def emitting(emitted: () => Unit): EmissionStep =
        EmissionStep(() =>
          emitted()
          Nil
        )

    /** The steps taken in order, each step's own steps before the steps after
      * it.
      */
    @scala.annotation.tailrec
    private def emittedInOrder(pending: List[EmissionStep]): Unit =
      pending match
        case Nil          => ()
        case step :: rest => emittedInOrder(step.taken() ::: rest)

    /** The emission of one method's expressions: its literals' indexes in the
      * class's data, the recursion it is (its number and parameters), the slot
      * of each binder, the next slot free and the stop signal's slot.
      */
    private final case class Emission(
        code: CodeBuilder,
        literalIndex: Map[Configured[C], Int],
        recursion: Option[(Int, Int)],
        slots: Map[Int, Int],
        nextSlot: Int,
        stopSlot: Int
    ):

      /** The expression's bytecode, emitted on the code builder. Stack-safe: a
        * loop over a list of steps (`EmissionStep`), each expression replaced
        * by its parts' steps and the bytecode around them, so an expression
        * nested as deep as a program's term is emitted without a JVM frame per
        * level.
        */
      def emitted(expression: NarrowExpression[Configured[C]]): Unit =
        emittedInOrder(List(EmissionStep.expression(expression, this)))

      /** The steps that emit the expression, in the order of its bytecode. */
      def steps(
          expression: NarrowExpression[Configured[C]]
      ): List[EmissionStep] = expression match
        case NarrowExpression.Literal(literal) =>
          List(EmissionStep.emitting(() =>
            code.ldc(
              DynamicConstantDesc.ofNamed(
                ConstantDescs.BSM_CLASS_DATA_AT,
                ConstantDescs.DEFAULT_NAME,
                bigInteger,
                Integer.valueOf(literalIndex(literal))
              )
            )
            ()
          ))
        case NarrowExpression.Folded(literal, _) =>
          steps(NarrowExpression.Literal(literal))
        case NarrowExpression.ClosedCode(closedCode, environment) =>
          List(
            EmissionStep.expression(
              NarrowExpression.Literal(
                NarrowBlockCompilation.instantiated(closedCode, environment)
              ),
              this
            )
          )
        case NarrowExpression.Value(closedValue) =>
          reader.closed(closedValue) match
            case Some(read) => List(EmissionStep.expression(read, this))
            case None       =>
              throw IllegalStateException(
                s"a closed natural does not read: $closedValue"
              )
        case NarrowExpression.Variable(binder) =>
          List(EmissionStep.emitting(() =>
            code.aload(slots(binder))
            ()
          ))
        case NarrowExpression.Native(name, arguments) =>
          operandSteps(arguments) :+ EmissionStep.emitting(() =>
            NarrowBlockCompilation.operations.get((name, arguments.size)) match
              case Some(operation) => operation.emitted(code, bigInteger)
              case None            =>
                val method = staticMethod(name, arguments.size)
                  .getOrElse(
                    throw IllegalStateException(
                      s"a native with no operation and no static method: $name"
                    )
                  )
                code.invokestatic(
                  ClassDesc.of(method.className),
                  method.methodName,
                  nativeMethodType(arguments.size)
                )
                ()
          )
        case NarrowExpression.PartialApplication(partial, _) =>
          throw IllegalStateException(
            s"a partial application the reader did not expand: $partial"
          )
        case NarrowExpression.Call(function, arguments) =>
          generatedCalled(
            code,
            stopSlot,
            s"function${functionNumbers((function, false))}",
            arguments.size
          )(operandSteps(arguments))
        case NarrowExpression.SelfCall(arguments) =>
          val (number, parameters) = recursion.getOrElse(
            throw IllegalStateException("a self call outside a recursion")
          )
          generatedCalled(code, stopSlot, s"function$number", parameters)(
            operandSteps(arguments)
          )
        case NarrowExpression.RecursionCall(body, arguments) =>
          generatedCalled(
            code,
            stopSlot,
            s"function${functionNumbers((body, true))}",
            arguments.size
          )(operandSteps(arguments))
        case NarrowExpression.Let(binder, value, body) =>
          List(
            EmissionStep.expression(value, this),
            EmissionStep.emitting(() =>
              code.astore(nextSlot)
              ()
            ),
            EmissionStep.expression(
              body,
              copy(
                slots = slots.updated(binder, nextSlot),
                nextSlot = nextSlot + 1
              )
            )
          )
        case NarrowExpression.Branch(
              scrutinee,
              zero,
              evenHalf,
              even,
              oddHalf,
              odd
            ) =>
          val scrutineeSlot = nextSlot
          val halfSlot = nextSlot + 1
          val inner = copy(nextSlot = nextSlot + 2)
          val nonZero = code.newLabel()
          val oddCase = code.newLabel()
          val end = code.newLabel()
          List(
            EmissionStep.expression(scrutinee, this),
            EmissionStep.emitting(() =>
              code.astore(scrutineeSlot)
              code
                .aload(scrutineeSlot)
                .invokevirtual(
                  bigInteger,
                  "signum",
                  MethodTypeDesc.of(ConstantDescs.CD_int)
                )
              code.ifne(nonZero)
              ()
            ),
            EmissionStep.expression(zero, inner),
            EmissionStep.emitting(() =>
              code.goto_(end)
              code.labelBinding(nonZero)
              code
                .aload(scrutineeSlot)
                .iconst_1()
                .invokevirtual(
                  bigInteger,
                  "shiftRight",
                  MethodTypeDesc.of(bigInteger, ConstantDescs.CD_int)
                )
              code.astore(halfSlot)
              code
                .aload(scrutineeSlot)
                .iconst_0()
                .invokevirtual(
                  bigInteger,
                  "testBit",
                  MethodTypeDesc
                    .of(ConstantDescs.CD_boolean, ConstantDescs.CD_int)
                )
              code.ifne(oddCase)
              ()
            ),
            EmissionStep.expression(
              even,
              inner.copy(slots = inner.slots.updated(evenHalf, halfSlot))
            ),
            EmissionStep.emitting(() =>
              code.goto_(end)
              code.labelBinding(oddCase)
              ()
            ),
            EmissionStep.expression(
              odd,
              inner.copy(slots = inner.slots.updated(oddHalf, halfSlot))
            ),
            EmissionStep.emitting(() =>
              code.labelBinding(end)
              ()
            )
          )

      /** The steps that push the operands, in order. */
      private def operandSteps(
          arguments: Vector[NarrowExpression[Configured[C]]]
      ): List[EmissionStep] =
        arguments.toList.map(EmissionStep.expression(_, this))

/** The operations of the natives a narrow block calls. */
object NarrowBlockCompilation:

  /** The closed term of a code read at the closed terms of its slots.
    * Stack-safe: read on `scala.util.control.TailCalls`.
    */
  def instantiated[C <: NativeSpecializer & Singleton](
      code: com.yang_bo.gezi.ir.Code,
      environment: Map[Int, Configured[C]]
  )(using C): Configured[C] =
    instantiation(code, environment).result

  private def instantiation[C <: NativeSpecializer & Singleton](
      code: com.yang_bo.gezi.ir.Code,
      environment: Map[Int, Configured[C]]
  )(using
      specializer: C
  ): TailRec[Configured[C]] =
    def both(left: com.yang_bo.gezi.ir.Code, right: com.yang_bo.gezi.ir.Code)(
        made: (Configured[C], Configured[C]) => Configured[C]
    ): TailRec[Configured[C]] =
      tailcall(instantiation(left, environment)).flatMap(instantiatedLeft =>
        tailcall(instantiation(right, environment)).map(
          made(instantiatedLeft, _)
        )
      )
    code.layer match
      case Slot(slot) =>
        done(
          environment.getOrElse(
            slot,
            throw IllegalStateException(
              s"the slot $slot of a closed code has no term"
            )
          )
        )
      case Apply(function, argument) =>
        both(function, argument)(specializer.application(_, _))
      case Parallel(left, right) =>
        both(left, right)(specializer.parallel(_, _))
      case Choice(left, right) => both(left, right)(specializer.choice(_, _))
      case Thunk(inner, holes, fillings) =>
        TailRecFolds
          .folded(fillings.toVector, Vector.empty[Configured[C]])(
            (made, filling) =>
              instantiation(filling, environment).map(made :+ _)
          )
          .map(filled =>
            com.yang_bo.gezi.ir.NonEmptyHoles.of(holes) match
              case Some(present) => specializer.thunk(inner, present, filled)
              case None          => specializer.instance(inner, filled)
          )

  /** Each item read, in order; nothing at the first item that does not read. A
    * reading of `scala.util.control.TailCalls`, so that it is stack-safe
    * however deep each item's reading goes.
    */
  private[narrowblocks] def allRead[Item, Read](items: Vector[Item])(
      read: Item => TailRec[Option[Read]]
  ): TailRec[Option[Vector[Read]]] =
    TailRecFolds.folded[Item, Option[Vector[Read]]](items, Some(Vector.empty)) {
      case (None, _)          => done(None)
      case (Some(made), item) => read(item).map(_.map(made :+ _))
    }

  /** native_types' contract, λd.λr.λf.λx. (f (x ∥ d)) ∥ r, as the front end
    * writes it: a constructor under it, `arrow D R C`, is C on an argument D
    * admits, giving a value R admits, by β.
    */
  lazy val contract: com.yang_bo.gezi.ir.Pure =
    import com.yang_bo.gezi.frontend.Term.λ
    Defunctionalization.pure(
      λ(domain =>
        λ(range =>
          λ(function => λ(argument => function(argument ∥ domain) ∥ range))
        )
      ).deBruijnTerm(Map.empty)
    )

  /** A native's operation on its operands on the stack, leaving its result. */
  final case class Operation(
      method: String,
      extra: Option[Int],
      thenSetsBit: Boolean
  ):

    /** The bytes of code `emitted` writes, at most: the constant loaded
      * (`iconst` one byte, `bipush` two, `sipush` or an `ldc_w` three), an
      * `invokevirtual` or a `getstatic`, and `iconst_0` with an `invokevirtual`
      * when it sets the low bit.
      */
    def codeSizeBound: Int =
      val constant = extra.fold(0)(value =>
        if value >= -1 && value <= 5 then 1
        else if value >= Byte.MinValue && value <= Byte.MaxValue then 2
        else 3
      )
      constant + 3 + (if thenSetsBit then 4 else 0)

    def emitted(code: CodeBuilder, bigInteger: ClassDesc): Unit =
      extra match
        case Some(constant) =>
          code.loadConstant(Integer.valueOf(constant))
          code.invokevirtual(
            bigInteger,
            method,
            MethodTypeDesc.of(bigInteger, ConstantDescs.CD_int)
          )
        case None =>
          if method == "ZERO" then
            code.getstatic(bigInteger, "ZERO", bigInteger)
          else
            code.invokevirtual(
              bigInteger,
              method,
              MethodTypeDesc.of(bigInteger, bigInteger)
            )
      if thenSetsBit then
        code.iconst_0()
        code.invokevirtual(
          bigInteger,
          "setBit",
          MethodTypeDesc.of(bigInteger, ConstantDescs.CD_int)
        )
      ()

  /** The operation of each of the binary naturals' constructors, the
    * framework's own natives, by its name and its operands' count. An entry's
    * natives are called through their `StaticBlockMethod`s.
    */
  val operations: Map[(NativeName, Int), Operation] = Map(
    (BinaryNaturalFamily.zeroNative, 0) -> Operation("ZERO", None, false),
    (BinaryNaturalFamily.evenNative, 1) -> Operation(
      "shiftLeft",
      Some(1),
      false
    ),
    (BinaryNaturalFamily.oddNative, 1) -> Operation("shiftLeft", Some(1), true)
  )
