package com.yang_bo.gezi.narrowblocks

package lists

import java.math.BigInteger
import scala.collection.immutable.HashMap

/** The memo of one run of a narrow block ([[com.yang_bo.gezi.narrowblocks.lists]], THE
  * MEMO): the values of the recursions' calls that have returned in the run, by
  * the recursion called and its arguments' run-time values. A persistent map
  * threaded through the run: every generated method, a block's and a
  * function's, takes the memo before its call and returns its value with the
  * memo after it (`Returned`), and a run (`NarrowBlockProgram.run`) starts from
  * `empty` and drops the memo when it returns. A recursion's method looks its
  * key up on entry and records it only once its body has returned, so a call
  * re-entered while in progress finds nothing and is evaluated as without the
  * memo: the memo answers from finished calls only, applies to every call of
  * every recursion alike, and emptying it changes only time.
  *
  * `retained` says whether a return is recorded: a memo that retains none,
  * `NarrowMemo.forgetting`, is the memo emptied before every call, which the
  * clearing law compares with. `recorded` counts the returns of recursions'
  * bodies, one for each body evaluated to its value, whether or not it was
  * retained: the count law's measure.
  *
  * The generated bytecode calls `key`, `withArgument`, `found`, `returned`,
  * `recordedReturn`, `value` and `memo` by name, as it calls `NarrowList`'s
  * methods: a name or a signature changed here is changed in
  * `NarrowBlockCompilation` too.
  */
final case class NarrowMemo(
    entries: HashMap[NarrowMemo.Key, AnyRef],
    retained: Boolean,
    recorded: Long
):

  /** The value recorded under the key, or null when there is none: the
    * generated code's "nothing", as a generated method's null is.
    */
  def found(key: NarrowMemo.Key): AnyRef = entries.getOrElse(key, null)

  /** The value returned with this memo. */
  def returned(value: AnyRef): NarrowMemo.Returned =
    NarrowMemo.Returned(value, this)

  /** The value returned with this memo and the value recorded under the key,
    * the record made after the call's body returned.
    */
  def recordedReturn(value: AnyRef, key: NarrowMemo.Key): NarrowMemo.Returned =
    NarrowMemo.Returned(
      value,
      NarrowMemo(
        if retained then entries.updated(key, value) else entries,
        retained,
        recorded + 1
      )
    )

object NarrowMemo:

  /** The memo of a run's start: no call has returned. */
  val empty: NarrowMemo = NarrowMemo(HashMap.empty, true, 0)

  /** The memo that retains no return, so that every call evaluates its body:
    * the memo emptied before every call.
    */
  val forgetting: NarrowMemo = NarrowMemo(HashMap.empty, false, 0)

  /** What a generated function returns: its value and the memo after its call.
    */
  final case class Returned(value: AnyRef, memo: NarrowMemo)

  /** A call's key: the number of the recursion called and its arguments' keys,
    * in order.
    */
  final case class Key(function: Int, arguments: Vector[ArgumentKey]):

    /** The key with one more argument after the others. Throws
      * `IllegalArgumentException` for a value of none of a block's
      * representations, a defect of the generated code.
      */
    def withArgument(value: AnyRef): Key =
      Key(function, arguments :+ ArgumentKey.of(value))

  /** The key of a call of the recursion numbered `function` with no argument
    * yet.
    */
  def key(function: Int): Key = Key(function, Vector.empty)

  /** An argument's key: a natural and a boolean by their values, a list by the
    * pair of its decode point and its start. Every list of a run is a suffix of
    * a list one literal decoded at compile time, since a block builds no list,
    * so the pair determines the list within the run; keying a list by its
    * elements would hash up to the whole list at every call.
    */
  enum ArgumentKey:
    case Natural(value: BigInteger)
    case ListAt(decodePoint: DecodePoint, start: Int)
    case Truth(value: Boolean)

    /** A list of records, by reference (`NarrowRecords`). */
    case RecordsAt(records: NarrowRecords)

  object ArgumentKey:

    /** The key of a value of a block. Throws `IllegalArgumentException` for a
      * value of none of a block's representations.
      */
    def of(value: AnyRef): ArgumentKey = value match
      case natural: BigInteger => ArgumentKey.Natural(natural)
      case list: NarrowList    =>
        ArgumentKey.ListAt(DecodePoint(list.elements), list.start)
      case truth: java.lang.Boolean => ArgumentKey.Truth(truth.booleanValue)
      case records: NarrowRecords   => ArgumentKey.RecordsAt(records)
      case other                    =>
        throw IllegalArgumentException(
          s"a narrow block's value is no natural, list, boolean or list of records: $other"
        )

  /** The decode point of a list, its elements as one literal decoded them,
    * compared by reference: two decode points of equal lists are two points, a
    * miss and never a wrong hit.
    */
  final class DecodePoint(val elements: Vector[BigInteger]):
    override def equals(other: Any): Boolean = other match
      case point: DecodePoint => point.elements eq elements
      case _                  => false
    override def hashCode: Int = System.identityHashCode(elements)
