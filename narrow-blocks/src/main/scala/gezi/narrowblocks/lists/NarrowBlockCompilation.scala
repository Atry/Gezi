/** A narrow block compiled into a class: its natural, or nothing when `stop`
  * asked for a stop before the block finished or the block gives no value
  * (`run`). The signal is read on entry to every recursion's method, once per
  * recursive call; a block that calls no recursion runs a bounded number of
  * operations and never reads it.
  */
trait NarrowBlockProgram:

  /** The generated class's method: the natural with the memo after the run
    * from `memo` ([[NarrowMemo]]), or null. Null is the
    * generated bytecode's "nothing", made by the stop's read and by a value
    * read in a representation it does not have (a narrow list read as a
    * natural, a natural read as a list, another value read as a boolean),
    * and returned through
    * every generated call (`NarrowBlockCompilation`'s `stopPolled`,
    * `naturalChecked`, `listChecked`, `truthChecked` and `generatedCalled`); no Scala source writes or reads
    * it but `ranWith`, the one boundary, which tells a stop from no value by
    * the signal. The value of a returned run is a `BigInteger`, checked by
    * the block's method.
    */
  def computed(stop: StopSignal, memo: NarrowMemo): NarrowMemo.Returned

  /** The natural with the memo after the run from `memo`, or nothing, as
    * `run` says: the laws' view of the memo (the clearing and count laws).
    */
  final def ranWith(stop: StopSignal, memo: NarrowMemo): Option[(BigInteger, NarrowMemo)] =
    Option(computed(stop, memo)).map(returned =>
      returned.value match
        case natural: BigInteger => (natural, returned.memo)
        case other               => throw IllegalStateException(s"a block's method returned no natural: $other")
    )

  /** The natural, or nothing when `stop` asked for a stop or the block gives
    * no value; `stop.stopRequested` tells the two apart. A block that gives no
    * value read a value in a representation it does not have, a list as a
    * natural, a natural as a list or another value as a boolean (a filter
    * that does not fit): nothing is answered, which loses an answer
    * and adds none, and the reader falls back.
    */
  final def run(stop: StopSignal): Option[BigInteger] = ranWith(stop, NarrowMemo.empty).map(_._1)

/** The narrow blocks of a program, compiled to JVM bytecode:
  * every closed
  * narrow natural of the program (`NarrowKind.Value`) is one method of one
  * hidden class, every closed function and recursion's body the program
  * calls one static method over values, each a `java.math.BigInteger` or a
  * `NarrowList`, a constructor of the binary naturals one operation of
  * `BigInteger`, a call of one of the entry's natives (`natives`) an
  * `invokestatic` of its implementation's `StaticBlockMethod`, and a branch
  * on a natural a test of its sign and its low bit. A closed term an operand
  * decodes, a literal, is decoded once at compile time, into a natural or a
  * narrow list (`constant`), and loaded from the class's data. A value read
  * as a natural (a native's operand, a branch's scrutinee, a block's result)
  * that the code does not know to be one is checked to be a `BigInteger`;
  * when it is not, the method gives no value (`naturalChecked`). That check
  * stands where no filter governs the value, a run-time check at a natural
  * read, not a filter of the term (`naturalOperandSteps`). The output is JVM
  * bytecode.
  *
  * A filter `e ∥ binary_set true` compiles to nothing: every natural the
  * block makes is canonical, a native's result or a decoded literal. A
  * literal filtered by `binary_set false` is decoded only when it is
  * positive. A block that reads another filter, a native whose
  * implementation is no `StaticBlockMethod` of as many places, or a literal
  * that does not decode is not compiled.
  *
  * The class is built with `java.lang.classfile`'s builders, a local
  * mutable exception (`CONTRIBUTING.md`, "The code is 100% immutable"):
  * they are used only inside `compiled`, and nothing they build is kept but the class's instance.
  */
/** A thunk of a program and the narrow check's reasons for refusing its
  * body, read as a recursion's body and as a closure's; nothing where it is
  * narrow (`NarrowBlockCompilation.thunkReadings`).
  */
final case class ThunkReading(thunk: Instruction, asRecursion: Option[String], asClosure: Option[String])

final case class NarrowBlockCompilation(index: StandardLibraryIndex, natives: NativeBackend):

  private val names: Map[Instruction, NarrowKind] =
    val backendNames = NarrowBlockExtractor.boundTerms(index) ++ index.combinatorProperties.map(_.instruction)
    // TODO (https://github.com/Atry/private-overlay/issues/1517):
    // the backend's names become the round's `leaves`.
    (index.noinline ++ backendNames + NarrowBlocks.fixpointByValue)
      .map(name => name -> NarrowBlocks.nameKind(name, index, natives))
      .toMap

  /** The static method a block calls for the entry's native of that name on
    * that many operands: its implementation when that is a
    * `StaticBlockMethod` of as many places with a result the block can hold
    * (`StaticBlockMethod.resultHeld`); none otherwise, and then a block that
    * calls the native is not compiled.
    */
  def staticMethod(name: NativeName, operands: Int): Option[StaticBlockMethod] =
    natives.natives
      .get(name)
      .filter(_.parameters.size == operands)
      .flatMap(native =>
        native.implementation match
          case method: StaticBlockMethod if StaticBlockMethod.resultHeld(native, method) => Some(method)
          case _                                                                         => None
      )

  /** Whether the entry's native of that name has a place
    * `NativePlace.NaturalList`, a backend fact of its binding.
    */
  private def takesNaturalList(name: NativeName): Boolean =
    natives.natives.get(name).exists(_.takesNaturalList)

  /** The representation of the binary naturals a criterion `binary_set p`
    * names, `p` read from the term.
    */
  private def binaryRepresentation(admitsZero: Boolean): Representation =
    if admitsZero then BinaryNaturalNatives.canonical else BinaryNaturalNatives.positive

  /** The representations the filters at the root of a closed operand name,
    * under applications of the identity: of the elements for a list's filter
    * `list_type (binary_set p)` when `list` holds, of the natural for
    * `binary_set p` otherwise. The representation is rebuilt from the kind's
    * `p` (`binaryRepresentation`) rather than read through the backend's
    * facts, which is exact while `binary_set` is the only criterion that
    * yields these kinds.
    */
  @scala.annotation.tailrec
  private def rootFilters(term: Instruction, list: Boolean, found: Set[Representation]): Set[Representation] =
    val bare = withoutIdentity(term)
    if bare.opaque then found
    else
      bare.layer match
        case Parallel(inner, criterion) =>
          val named = kinds(Vector(criterion)).get(criterion) match
            case Some(NarrowKind.ListCriterion(admitsZero)) if list  => Set(binaryRepresentation(admitsZero))
            case Some(NarrowKind.Criterion(admitsZero)) if !list     => Set(binaryRepresentation(admitsZero))
            case _                                                   => Set.empty[Representation]
          rootFilters(inner, list, found ++ named)
        case _ => found

  /** The closed term of an operand; none for an operand the block computes. */
  private def closedOperand(operand: NarrowExpression[Instruction]): Option[Instruction] = operand match
    case NarrowExpression.Literal(instruction) => Some(instruction)
    case NarrowExpression.Value(instruction)   => Some(instruction)
    case _                                     => None

  /** Whether an operand at the place is licensed: the representation the
    * place declares is among those known of the operand. Read as a natural,
    * every operand is known to be one of the block's naturals
    * (`StaticBlockMethod.blockNatural`): the block makes naturals only as
    * decoded literals and results `StaticBlockMethod.resultHeld` admits, and
    * checks at the read that a value it does not know to be a natural is one,
    * giving no value otherwise (`naturalChecked`). A closed operand is also
    * known to be what the filters at its root name. Read as a list, only a
    * closed operand's elements are known, by the filter `list_type c` at its
    * root. No other place is licensed. The host compares what the term's
    * filter names with the backend fact the native declares and decides
    * nothing by a type of its own.
    */
  private def placeLicensed(place: NativePlace, operand: NarrowExpression[Instruction]): Boolean =
    place match
      case NativePlace.NaturalList(element) =>
        closedOperand(operand).exists(rootFilters(_, true, Set.empty).contains(element))
      case NativePlace.Fixed(representation) =>
        representation == StaticBlockMethod.blockNatural ||
        closedOperand(operand).exists(rootFilters(_, false, Set.empty).contains(representation))
      case _ => false

  /** Whether every operand of a call of the native is licensed at its place.
    * A constructor of the binary naturals is one of the block's own
    * operations (`NarrowBlockCompilation.operations`), which takes the block's
    * naturals and has no place to compare.
    */
  private def operandsLicensed(name: NativeName, arguments: Vector[NarrowExpression[Instruction]]): Boolean =
    NarrowBlockCompilation.operations.contains((name, arguments.size)) ||
      natives.natives.get(name).exists(_.parameters.zip(arguments).forall(placeLicensed))

  /** The terms of the list's constructors, nil and cons: the term the
    * backend's facts bind to the framework's list family at each one's
    * position (`BackendFacts.bindings`, a `data_family` of a criterion whose
    * `native_specialization` names the list representation), when exactly
    * one term is bound at each; none otherwise, and then no literal decodes
    * as a list.
    */
  private val listConstructors: Option[(Instruction, Instruction)] =
    val bindings = BackendFacts.bindings(index, natives)
    def bound(constructor: ListConstructor): Option[Instruction] =
      bindings.collect {
        case NativeBinding(term, NativeName.Constructor(Representation.listFamily, position))
            if position == ListCodec.position(constructor) =>
          term
      }.distinct match
        case Vector(term) => Some(term)
        case _            => None
    for
      nil <- bound(ListConstructor.Nil)
      cons <- bound(ListConstructor.Cons)
    yield (nil, cons)

  /** The narrow kind of every subterm of the roots, a name's its own. */
  def kinds(roots: Vector[Instruction]): Map[Instruction, NarrowKind] =
    @scala.annotation.tailrec
    def visited(pending: List[(Instruction, Boolean)], found: Map[Instruction, NarrowKind]): Map[Instruction, NarrowKind] =
      pending match
        case Nil                                           => found
        case (instruction, _) :: rest if found.contains(instruction) => visited(rest, found)
        case (instruction, _) :: rest if names.contains(instruction) =>
          visited(rest, found.updated(instruction, names(instruction)))
        case (instruction, _) :: rest if instruction.opaque => visited(rest, found.updated(instruction, NarrowKind.Closed))
        case (instruction, false) :: rest =>
          visited(instruction.layer.children.toList.map((_, false)) ::: (instruction, true) :: rest, found)
        case (instruction, true) :: rest =>
          val kind = instruction.layer match
            case Apply(function, argument) => NarrowBlocks.applicationKind(found(function), found(argument))
            case Parallel(left, right)     => NarrowBlocks.parallelKind(found(left), found(right))
            case Choice(left, right)       => NarrowBlocks.choiceKind(Vector(found(left), found(right)))
            case Thunk(code, holes, fillings) =>
              NarrowBlocks.thunkKind(code, holes, fillings.map(filling => NarrowItem.Known(found(filling), filling))) match
                case NarrowKind.Closed if NarrowBlocks.readsAsIdentity(instruction) => NarrowKind.Identity
                case kind                                                          => kind
            case UriNode(_) | Opaque(_) => NarrowKind.Closed
          visited(rest, found.updated(instruction, kind))
    visited(roots.toList.map((_, false)), Map.empty)

  /** Every thunk of the program with the narrow check's verdict on its body,
    * in the order of a walk from the root, each thunk once: read as a
    * recursion's body (the self call allowed) and as a closure's, each the
    * reason of the first code no production reads (`NarrowBlocks.explained`),
    * or nothing when the body is narrow. A diagnostic for whoever writes
    * knowledge: why a typed loop of an extraction stays out of a block. No
    * decision of the framework reads it.
    */
  def thunkReadings(program: Instruction): Vector[ThunkReading] =
    val found = kinds(Vector(program))
    @scala.annotation.tailrec
    def walked(pending: List[Instruction], seen: Set[Instruction], made: Vector[ThunkReading]): Vector[ThunkReading] =
      pending match
        case Nil                                                                          => made
        case instruction :: rest if seen(instruction) || instruction.opaque || names.contains(instruction) =>
          walked(rest, seen + instruction, made)
        case instruction :: rest =>
          val reading = instruction.layer match
            case Thunk(code, holes, fillings) =>
              val items = fillings.map(filling => NarrowItem.Known(found.getOrElse(filling, NarrowKind.Closed), filling))
              Vector(
                ThunkReading(
                  instruction,
                  NarrowBlocks.explained(code, holes, items, recursion = true).left.toOption,
                  NarrowBlocks.explained(code, holes, items, recursion = false).left.toOption
                )
              )
            case _ => Vector.empty
          walked(instruction.layer.children.toList ::: rest, seen + instruction, made ++ reading)
    walked(List(program), Set.empty, Vector.empty)

  /** The maximal closed narrow naturals of the program, in the order of a
    * walk from its root, a subterm before those under it; a canonical
    * numeral (`decoded`) is none, being its own value, nor is anything under
    * it. Without that, the numerals of a list literal outside every block,
    * each a closed narrow natural once the list's cons is no native of a
    * natural, were a block each, compiled and run to give themselves back.
    */
  def blocks(program: Instruction): Vector[Instruction] = locatedBlocks(program, SourceMap.unlocated).map(_._1)

  /** The blocks of the program (`blocks`) with the map of each one's
    * occurrence, the map walked beside the program by `Layer.children`: the
    * place of a block met twice is its first occurrence's, and a place the
    * map leaves bare has its subterms unlocated. Throws
    * `IllegalArgumentException` for a map of another shape than the program
    * where it locates anything below a place.
    */
  def locatedBlocks(program: Instruction, map: SourceMap): Vector[(Instruction, SourceMap)] =
    val found = kinds(Vector(program))
    @scala.annotation.tailrec
    def walked(
        pending: List[(Instruction, SourceMap)],
        seen: Set[Instruction],
        made: Vector[(Instruction, SourceMap)]
    ): Vector[(Instruction, SourceMap)] =
      pending match
        case Nil                                             => made
        case (instruction, _) :: rest if seen(instruction) => walked(rest, seen, made)
        case (instruction, placed) :: rest if found.get(instruction).contains(NarrowKind.Value) =>
          if decoded(instruction).isDefined then walked(rest, seen + instruction, made)
          else walked(rest, seen + instruction, made :+ (instruction, placed))
        case (instruction, _) :: rest if instruction.opaque || names.contains(instruction) =>
          walked(rest, seen + instruction, made)
        case (instruction, placed) :: rest =>
          val children = instruction.layer.children
          require(
            placed.children.isEmpty || placed.children.size == children.size,
            s"a map of ${placed.children.size} places below ${children.size} subterms"
          )
          val childMaps = if placed.children.isEmpty then Vector.fill(children.size)(SourceMap.unlocated) else placed.children
          walked(children.zip(childMaps).toList ::: rest, seen + instruction, made)
    walked(List((program, map)), Set.empty, Vector.empty)

  /** The blocks compiled into one class, one method each, when every block
    * compiles, with the debugging attributes asked for; otherwise why not.
    */
  def compiled(
      blockRoots: Vector[Instruction],
      debug: DebugAttributes,
      stop: StopSignal
  ): Either[String, Vector[NarrowBlockProgram]] =
    generation(blockRoots, debug, stop).flatMap(_.defined())

  /** The class file of the blocks, as `compiled` defines it; otherwise why
    * not. What a reader of the class, a debugger or a test, reads of it.
    */
  def classFile(
      blockRoots: Vector[Instruction],
      debug: DebugAttributes,
      stop: StopSignal
  ): Either[String, scala.collection.immutable.ArraySeq[Byte]] =
    generation(blockRoots, debug, stop).flatMap(_.classFile()).map(bytes => scala.collection.immutable.ArraySeq.unsafeWrapArray(bytes))

  /** The class's generation, when every block reads; the reading folds its
    * constants until the stop is asked for (`Reader`).
    */
  private def generation(blockRoots: Vector[Instruction], debug: DebugAttributes, stop: StopSignal): Either[String, Generation] =
    val found = kinds(blockRoots)
    val reader = Reader(found, stop)
    val roots = blockRoots.map(reader.closed)
    for
      expressions <- Either.cond(
        roots.forall(_.isDefined),
        roots.flatten,
        s"a block does not read: ${blockRoots.zip(roots).collectFirst { case (root, None) => root }}"
      )
      functions <- reader.functionsOf(expressions)
    yield Generation(found, reader, expressions, functions, DebugAttributes.lines(debug, blockRoots.size))

  /** The reading of closed terms into expressions, by their kinds. A native
    * applied to operands that read as literals or folded naturals is folded
    * (`folded`), until the stop is asked for: from then on nothing is folded,
    * so that a costly constant cannot hold a compilation that is asked to
    * stop, and the expression is emitted as read, which computes the same.
    */
  private final case class Reader(found: Map[Instruction, NarrowKind], stop: StopSignal):

    private def kind(instruction: Instruction): NarrowKind = found.getOrElse(instruction, NarrowKind.Closed)

    /** The term with the member of each outer choice that the backend
      * compiles chosen (`NarrowBlocks.chosenMember`), among the members of
      * the choice's whole right `+` spine, a right side that is a name
      * ending it.
      */
    @scala.annotation.tailrec
    private def chosen(instruction: Instruction): Instruction =
      if names.contains(instruction) || instruction.opaque then instruction
      else
        instruction match
          case Instruction.Choice(_, _) =>
            val members = gezi.ir.ChoiceSpine.members[Instruction](
              instruction,
              current =>
                if current != instruction && names.contains(current) then None else Instruction.Choice.unapply(current)
            )
            NarrowBlocks.chosenMember(members.map(kind)) match
              case Some(position) => chosen(members(position))
              case None           => instruction
          case _ => instruction

    /** The head of the term's application spine and its arguments, the
      * innermost application's argument first, each function position's
      * choice resolved (`chosen`). Stack-safe: a loop down the function
      * positions, the arguments gathered on the way.
      */
    private def spine(instruction: Instruction): (Instruction, Vector[Instruction]) =
      @scala.annotation.tailrec
      def unwound(current: Instruction, outerArguments: List[Instruction]): (Instruction, Vector[Instruction]) =
        val resolved = chosen(current)
        if names.contains(resolved) || resolved.opaque then (resolved, outerArguments.toVector)
        else
          resolved.layer match
            case Apply(function, argument) => unwound(function, argument :: outerArguments)
            case _                         => (resolved, outerArguments.toVector)
      unwound(instruction, Nil)

    /** The expression of a closed narrow natural. Stack-safe: read on
      * `scala.util.control.TailCalls`, so a natural nested as deep as a
      * program's term is read without a JVM frame per level.
      */
    def closed(instruction: Instruction): Option[NarrowExpression[Instruction]] =
      closedReading(instruction).result

    private def closedReading(instruction: Instruction): TailRec[Option[NarrowExpression[Instruction]]] =
      val resolved = chosen(instruction)
      if names.contains(resolved) || resolved.opaque then done(None)
      else
        resolved.layer match
          case Parallel(value, criterion) =>
            kind(criterion) match
              case NarrowKind.Criterion(true)  => tailcall(operand(value))
              case NarrowKind.Criterion(false) => done(Some(NarrowExpression.Literal(resolved)))
              case _                           => done(None)
          case Apply(_, _) =>
            val (head, arguments) = spine(resolved)
            kind(head) match
              case NarrowKind.Native(name, places, 0) if arguments.size == places =>
                tailcall(operands(arguments)).map(_.map(read => folded(resolved, name, read)))
              case NarrowKind.Fixpoint =>
                arguments.headOption match
                  case Some(body) =>
                    kind(body) match
                      case NarrowKind.Thunk(_, true, holes) if arguments.size == holes =>
                        tailcall(operands(arguments.tail)).map(_.map(NarrowExpression.RecursionCall(body, _)))
                      case _ => done(None)
                  case None => done(None)
              case NarrowKind.Thunk(true, _, holes) if arguments.size == holes =>
                tailcall(operands(arguments)).map(_.map(NarrowExpression.Call(head, _)))
              case _ => done(None)
          case _ => done(None)

    private def operand(instruction: Instruction): TailRec[Option[NarrowExpression[Instruction]]] =
      kind(instruction) match
        case NarrowKind.Closed | NarrowKind.Native(_, 0, 0) => done(Some(NarrowExpression.Literal(instruction)))
        case _                                               => tailcall(closedReading(instruction))

    /** The native's call on the operands read, folded into the natural it
      * computes when every operand's value is known (`valueOf`) and the
      * native's value on them is (`computed`), and the stop is not asked for;
      * otherwise the call. A fold reads the values of its operands only, each
      * a literal decoded or a natural folded already, so reading a natural
      * folds it in one pass, bottom up.
      */
    private def folded(
        closed: Instruction,
        name: NativeName,
        read: Vector[NarrowExpression[Instruction]]
    ): NarrowExpression[Instruction] =
      val call = NarrowExpression.Native(name, read)
      if stop.stopRequested then call
      else
        val values = read.map(valueOf)
        if values.forall(_.isDefined) && operandsLicensed(name, read) then
          computed(name, values.flatten).fold(call)(NarrowExpression.Folded(closed, _))
        else call

    /** The value of an operand read: a folded natural's, a literal's decoded
      * (`decoded`); none otherwise.
      */
    private def valueOf(read: NarrowExpression[Instruction]): Option[BigInt] = read match
      case NarrowExpression.Folded(_, value) => Some(value)
      case NarrowExpression.Literal(literal) => decoded(literal)
      case _                                 => None

    /** Each instruction read as an operand, in order; nothing at the first
      * that does not read, which is the same as reading them all, reading
      * being pure.
      */
    private def operands(instructions: Vector[Instruction]): TailRec[Option[Vector[NarrowExpression[Instruction]]]] =
      NarrowBlockCompilation.allRead(instructions)(operand)

    /** The body of a closed function, or of a recursion's when `recursion`. */
    def body(function: Instruction, recursion: Boolean): Option[NarrowExpression[Instruction]] =
      function.layer match
        case Thunk(code, holes, fillings) =>
          NarrowBlocks.body(code, holes, fillings.map(filling => NarrowItem.Known(kind(filling), filling)), recursion)
            .flatMap(fullCalls)
        case _ => None

    /** The expression with each call of a partial application
      * (`NarrowExpression.PartialApplication`) read as the full call of its
      * head: a native's call, or a recursion's call when the head is the
      * fixed point combinator, whose first operand is the recursion's body.
      * The partial application's own operands, each read as an operand, come
      * before the call's; none when one of them does not read. Every other
      * part is kept, read in turn. Stack-safe: read on
      * `scala.util.control.TailCalls`.
      */
    private def fullCalls(expression: NarrowExpression[Instruction]): Option[NarrowExpression[Instruction]] =
      fullCallsReading(expression).result

    private def fullCallsReading(expression: NarrowExpression[Instruction]): TailRec[Option[NarrowExpression[Instruction]]] =
      def all(expressions: Vector[NarrowExpression[Instruction]]): TailRec[Option[Vector[NarrowExpression[Instruction]]]] =
        NarrowBlockCompilation.allRead(expressions)(part => tailcall(fullCallsReading(part)))
      def withRest(
          suppliedOperands: Option[Vector[NarrowExpression[Instruction]]],
          arguments: Vector[NarrowExpression[Instruction]]
      )(made: Vector[NarrowExpression[Instruction]] => NarrowExpression[Instruction]): TailRec[Option[NarrowExpression[Instruction]]] =
        suppliedOperands match
          case None => done(None)
          case Some(read) => all(arguments).map(_.map(rest => made(read ++ rest)))
      expression match
        case NarrowExpression.PartialApplication(partial, arguments) =>
          val (head, supplied) = spine(chosen(partial))
          (kind(head), supplied) match
            case (NarrowKind.Native(name, _, 0), _) =>
              tailcall(operands(supplied)).flatMap(withRest(_, arguments)(NarrowExpression.Native(name, _)))
            case (NarrowKind.Fixpoint, body +: suppliedParameters) =>
              tailcall(operands(suppliedParameters)).flatMap(withRest(_, arguments)(NarrowExpression.RecursionCall(body, _)))
            case _ => done(None)
        case NarrowExpression.Native(name, arguments)        => all(arguments).map(_.map(NarrowExpression.Native(name, _)))
        case NarrowExpression.Call(function, arguments)      => all(arguments).map(_.map(NarrowExpression.Call(function, _)))
        case NarrowExpression.SelfCall(arguments)            => all(arguments).map(_.map(NarrowExpression.SelfCall(_)))
        case NarrowExpression.RecursionCall(body, arguments) => all(arguments).map(_.map(NarrowExpression.RecursionCall(body, _)))
        case NarrowExpression.Branch(scrutinee, zero, evenHalf, even, oddHalf, odd) =>
          all(Vector(scrutinee, zero, even, odd)).map(_.map {
            case Vector(readScrutinee, readZero, readEven, readOdd) =>
              NarrowExpression.Branch(readScrutinee, readZero, evenHalf, readEven, oddHalf, readOdd)
            case other => throw IllegalStateException(s"four parts of a branch, not ${other.size}")
          })
        case NarrowExpression.ListBranch(scrutinee, nil, headBinder, tailBinder, cons) =>
          all(Vector(scrutinee, nil, cons)).map(_.map {
            case Vector(readScrutinee, readNil, readCons) =>
              NarrowExpression.ListBranch(readScrutinee, readNil, headBinder, tailBinder, readCons)
            case other => throw IllegalStateException(s"three parts of a list branch, not ${other.size}")
          })
        case NarrowExpression.Filtered(value, representation) =>
          tailcall(fullCallsReading(value)).map(_.map(NarrowExpression.Filtered(_, representation)))
        case NarrowExpression.Select(scrutinee, whenTrue, whenFalse) =>
          all(Vector(scrutinee, whenTrue, whenFalse)).map(_.map {
            case Vector(readScrutinee, readTrue, readFalse) => NarrowExpression.Select(readScrutinee, readTrue, readFalse)
            case other => throw IllegalStateException(s"three parts of a boolean's branch, not ${other.size}")
          })
        case NarrowExpression.Let(binder, value, body) =>
          tailcall(fullCallsReading(value)).flatMap {
            case None            => done(None)
            case Some(readValue) => tailcall(fullCallsReading(body)).map(_.map(NarrowExpression.Let(binder, readValue, _)))
          }
        case other => done(Some(other))

    /** Every function and recursion's body the expressions call, with its
      * body, closed under the calls of those bodies; nothing when one does
      * not read.
      */
    def functionsOf(
        expressions: Vector[NarrowExpression[Instruction]]
    ): Either[String, Vector[(Instruction, Boolean, NarrowExpression[Instruction])]] =
      @scala.annotation.tailrec
      def closedOver(
          pending: List[(Instruction, Boolean)],
          made: Vector[(Instruction, Boolean, NarrowExpression[Instruction])]
      ): Either[String, Vector[(Instruction, Boolean, NarrowExpression[Instruction])]] =
        pending match
          case Nil => Right(made)
          case (function, recursion) :: rest if made.exists((other, otherRecursion, _) => other == function && otherRecursion == recursion) =>
            closedOver(rest, made)
          case (function, recursion) :: rest =>
            body(function, recursion) match
              case None => Left(s"a function's body does not read (recursion $recursion): $function")
              case Some(read) =>
                closedOver(calls(read).toList ::: rest, made :+ (function, recursion, read))
      closedOver(expressions.flatMap(calls).toList, Vector.empty)

    /** The functions and recursions' bodies an expression calls, closed
      * naturals inside it read in turn: in preorder, a call before the calls
      * in its operands, the parts left to right. Stack-safe: a loop over the
      * parts still to walk.
      */
    def calls(expression: NarrowExpression[Instruction]): Vector[(Instruction, Boolean)] =
      @scala.annotation.tailrec
      def walked(
          pending: List[NarrowExpression[Instruction]],
          made: Vector[(Instruction, Boolean)]
      ): Vector[(Instruction, Boolean)] =
        pending match
          case Nil => made
          case next :: rest =>
            next match
              case NarrowExpression.Literal(_) | NarrowExpression.Folded(_, _) | NarrowExpression.ClosedCode(_, _) =>
                walked(rest, made)
              case NarrowExpression.Value(closedValue) => walked(closed(closedValue).toList ::: rest, made)
              case NarrowExpression.Variable(_)          => walked(rest, made)
              case NarrowExpression.Native(_, arguments) => walked(arguments.toList ::: rest, made)
              case NarrowExpression.PartialApplication(partial, _) =>
                throw IllegalStateException(s"a partial application the reader did not expand: $partial")
              case NarrowExpression.Call(function, arguments) => walked(arguments.toList ::: rest, made :+ (function, false))
              case NarrowExpression.SelfCall(arguments)       => walked(arguments.toList ::: rest, made)
              case NarrowExpression.RecursionCall(body, arguments) => walked(arguments.toList ::: rest, made :+ (body, true))
              case NarrowExpression.Branch(scrutinee, zero, _, even, _, odd) =>
                walked(scrutinee :: zero :: even :: odd :: rest, made)
              case NarrowExpression.ListBranch(scrutinee, nil, _, _, cons) => walked(scrutinee :: nil :: cons :: rest, made)
              case NarrowExpression.Filtered(value, _)                     => walked(value :: rest, made)
              case NarrowExpression.Select(scrutinee, whenTrue, whenFalse) =>
                walked(scrutinee :: whenTrue :: whenFalse :: rest, made)
              case NarrowExpression.Let(_, value, body) => walked(value :: body :: rest, made)
      walked(List(expression), Vector.empty)

  /** A literal decoded at compile time: a canonical binary natural built of
    * the constructors' natives, each under its filters, or under the
    * contract `arrow D R C` (native_types', read by its term), a filter or
    * a contract's domain and range read at their parameters, an application
    * of the identity read as its argument; nothing for any other term. A
    * noinline name's instruction is its own layer (hash consing), read the
    * same way. Stack-safe and cheap on any other term: a loop down the
    * arguments that stops at the first layer that is none of these, before
    * reading what is under it, so a term thousands of calls deep that is no
    * numeral costs one step (`locatedBlocks` asks it of every closed
    * natural); the steps met on the way are applied from the innermost out.
    */
  private def decoded(instruction: Instruction): Option[BigInt] =
    @scala.annotation.tailrec
    def walked(current: Instruction, outerSteps: List[BigInt => Option[BigInt]]): Option[BigInt] =
      names.get(current) match
        case Some(NarrowKind.Native(BinaryNaturalFamily.zeroNative, 0, 0)) =>
          outerSteps.foldLeft(Option(BigInt(0)))((value, step) => value.flatMap(step))
        case _ if current.opaque => None
        case _ =>
          current.layer match
            case Parallel(value, criterion) =>
              walked(value, ((field: BigInt) => Option.when(admitted(criterion, field))(field)) :: outerSteps)
            case Apply(function, argument) =>
              if constructorNative(function) then walked(argument, ((field: BigInt) => constructed(function, field)) :: outerSteps)
              else if kinds(Vector(function)).get(function).contains(NarrowKind.Identity) then walked(argument, outerSteps)
              else
                contracted(function) match
                  case Some((domain, range, constructor)) =>
                    walked(
                      argument,
                      ((field: BigInt) =>
                        if admitted(domain, field) then constructed(constructor, field).filter(admitted(range, _)) else None
                      ) :: outerSteps
                    )
                  case None => None
            case _ => None
    walked(instruction, Nil)

  /** Whether the term is a constructor of the binary naturals with a field,
    * even or odd, by the native it is bound to.
    */
  private def constructorNative(function: Instruction): Boolean =
    names.get(function) match
      case Some(NarrowKind.Native(BinaryNaturalFamily.evenNative, 1, 0)) => true
      case Some(NarrowKind.Native(BinaryNaturalFamily.oddNative, 1, 0))  => true
      case _                                                             => false

  /** The value of a native's call on the values given, computed at compile
    * time as the block would compute it: the binary naturals' constructors
    * as `constructed` reads a canonical natural (so that no fold makes the
    * non-canonical `even zero`, which is then left to the code), and any
    * other native by its static method (`staticMethod`) when that gives a
    * natural, invoked as the block's `invokestatic` would invoke it; none
    * for any other native.
    */
  private def computed(name: NativeName, values: Vector[BigInt]): Option[BigInt] =
    (name, values) match
      case (BinaryNaturalFamily.zeroNative, Vector())     => Some(BigInt(0))
      case (BinaryNaturalFamily.evenNative, Vector(field)) => Option.when(field > 0)(field * 2)
      case (BinaryNaturalFamily.oddNative, Vector(field))  => Some(field * 2 + 1)
      case _ =>
        staticMethod(name, values.size).filter(method => method.result == StaticBlockResult.Natural && !takesNaturalList(name)).map(method =>
          val handle = MethodHandles
            .publicLookup()
            .findStatic(
              Class.forName(method.className, true, getClass.getClassLoader),
              method.methodName,
              java.lang.invoke.MethodType.methodType(classOf[BigInteger], java.util.Collections.nCopies(values.size, classOf[BigInteger]))
            )
          handle.invokeWithArguments(java.util.List.of(values.map(_.bigInteger)*)) match
            case result: BigInteger => BigInt(result)
            case other => throw IllegalStateException(s"the static method of $name returned no natural: $other")
        )

  /** The natural a constructor's native makes of its field. */
  private def constructed(constructor: Instruction, field: BigInt): Option[BigInt] =
    names.get(constructor) match
      case Some(NarrowKind.Native(BinaryNaturalFamily.evenNative, 1, 0)) if field > 0 => Some(field * 2)
      case Some(NarrowKind.Native(BinaryNaturalFamily.oddNative, 1, 0))               => Some(field * 2 + 1)
      case _                                                                         => None

  /** Whether the criterion `binary_set p` admits the canonical natural. */
  private def admitted(criterion: Instruction, number: BigInt): Boolean =
    kinds(Vector(criterion)).get(criterion) match
      case Some(NarrowKind.Criterion(admitsZero)) => admitsZero || number > 0
      case _                                      => false

  /** A literal decoded at compile time into the constant the block reads: a
    * canonical natural (`decoded`), else a narrow list filtered at its root
    * (`listDecoded`), else a boolean filtered by the booleans' criterion
    * (`truthDecoded`); none when it is none of these, nil written with no
    * filter among them. No term is two of them: a natural's constructors and
    * a list's are other terms of other families, and nil, which is the term
    * of true, is a list only under a list's filter and a boolean only under
    * the booleans'.
    */
  def constant(instruction: Instruction): Option[NarrowConstant] =
    decoded(instruction)
      .map(NarrowConstant.Natural(_))
      .orElse(listDecoded(instruction).map(NarrowConstant.ListOf(_)))
      .orElse(truthDecoded(instruction).map(NarrowConstant.Truth(_)))

  /** A boolean literal decoded at compile time:
    * `b ∥ boolean_type`, b true or false by its structure
    * (`NarrowKind.Truth`), under applications of the identity; none for any
    * other term, a bare boolean included, which no filter of the term says
    * is one.
    */
  private def truthDecoded(instruction: Instruction): Option[Boolean] =
    if instruction.opaque then None
    else
      withoutIdentity(instruction).layer match
        case Parallel(value, criterion) if kinds(Vector(criterion)).get(criterion).contains(NarrowKind.BooleanCriterion) =>
          kinds(Vector(value)).get(value).collect { case NarrowKind.Truth(truth) => truth }
        case _ => None

  /** A list literal decoded at compile time into a narrow list: a
    * list built of the backend's list constructors (`listConstructors`), its
    * elements canonical naturals as `decoded` reads them, under applications
    * of the identity and under filters `∥ list_type (binary_set p)`, one at
    * the list's root and any at its tails, each filter's criterion admitting
    * every element from its place on; the whole list from its first element.
    * None for any other term: a list with no filter at its root, a choice,
    * another filter, an element that does not decode, a filter an element
    * does not meet. The filter at the root is what licenses the
    * representation (`CONTRIBUTING.md`, "Types live only in the term"): the list's
    * family is never read from its constructors alone. Every element of a narrow list is a
    * canonical natural, so the filter `∥ list_type (binary_set true)` holds
    * of every narrow list. Stack-safe: a loop down the tails.
    */
  def listDecoded(instruction: Instruction): Option[NarrowList] =
    listConstructors.flatMap { (nil, cons) =>
      @scala.annotation.tailrec
      def walked(current: Instruction, elements: Vector[BigInt], filters: List[(Int, Boolean)]): Option[(Vector[BigInt], List[(Int, Boolean)])] =
        if current == nil then Some((elements, filters))
        else if current.opaque then None
        else
          current.layer match
            case Parallel(inner, criterion) =>
              kinds(Vector(criterion)).get(criterion) match
                case Some(NarrowKind.ListCriterion(admitsZero)) => walked(inner, elements, (elements.size, admitsZero) :: filters)
                case _                                         => None
            case Apply(function, rest) =>
              consedElement(function, cons) match
                case Some(element) =>
                  decoded(element) match
                    case Some(value) => walked(rest, elements :+ value, filters)
                    case None        => None
                case None if kinds(Vector(function)).get(function).contains(NarrowKind.Identity) => walked(rest, elements, filters)
                case None                                                                        => None
            case _ => None
      walked(instruction, Vector.empty, Nil).collect {
        case (elements, filters) if filters.exists(_._1 == 0) && filters.forall((from, admitsZero) => admitsZero || elements.drop(from).forall(_ > 0)) =>
          NarrowList(elements.map(_.bigInteger), 0)
      }
    }

  /** The element of `cons e`, a cons applied to its element under
    * applications of the identity, when the function of a list's
    * application is one; none otherwise.
    */
  private def consedElement(function: Instruction, cons: Instruction): Option[Instruction] =
    if function.opaque then None
    else
      function.layer match
        case Apply(head, element) if withoutIdentity(head) == cons => Some(element)
        case _                                                     => None

  /** The domain, the range and the function of a term `arrow D R C`, the
    * contract read by its term under applications of the identity.
    */
  private def contracted(term: Instruction): Option[(Instruction, Instruction, Instruction)] =
    if term.opaque then None
    else
      term.layer match
        case Apply(partial, function) =>
          partial.layer match
            case Apply(head, range) =>
              head.layer match
                case Apply(contractTerm, domain) if withoutIdentity(contractTerm) == NarrowBlockCompilation.contract =>
                  Some((domain, range, function))
                case _ => None
            case _ => None
        case _ => None

  /** The term with every application of the identity at its root taken off. */
  @scala.annotation.tailrec
  private def withoutIdentity(term: Instruction): Instruction =
    if term.opaque then term
    else
      term.layer match
        case Apply(function, argument) if kinds(Vector(function)).get(function).contains(NarrowKind.Identity) =>
          withoutIdentity(argument)
        case _ => term

  /** The class of the blocks and the functions they call. */
  private final case class Generation(
      found: Map[Instruction, NarrowKind],
      reader: Reader,
      blocks: Vector[NarrowExpression[Instruction]],
      functions: Vector[(Instruction, Boolean, NarrowExpression[Instruction])],
      lines: Option[ClassLines]
  ):

    private val bigInteger = ClassDesc.of("java.math.BigInteger")
    private val narrowList = ClassDesc.of("gezi.narrowblocks.lists.NarrowList")
    private val naturalListElements = ClassDesc.of("scala.collection.immutable.Vector")
    private val boxedTruth = ConstantDescs.CD_Boolean
    private val generatedClass = ClassDesc.of("gezi.narrowblocks.lists.GeneratedNarrowBlock")
    private val programInterface = ClassDesc.of("gezi.narrowblocks.lists.NarrowBlockProgram")
    private val stopSignal = ClassDesc.of("gezi.saturation.StopSignal")
    private val memo = ClassDesc.of("gezi.narrowblocks.lists.NarrowMemo")
    private val memoModule = ClassDesc.of("gezi.narrowblocks.lists.NarrowMemo$")
    private val memoKey = ClassDesc.of("gezi.narrowblocks.lists.NarrowMemo$Key")
    private val memoReturned = ClassDesc.of("gezi.narrowblocks.lists.NarrowMemo$Returned")
    private val objectClass = ConstantDescs.CD_Object

    /** The type of a native's static method: its operands to its result in
      * the JVM convention the method declares (`StaticBlockMethod.result`), a
      * `BigInteger` or a JVM `boolean`.
      */
    private def nativeMethodType(name: NativeName, result: StaticBlockResult): MethodTypeDesc =
      val resultType = result match
        case StaticBlockResult.Natural => bigInteger
        case StaticBlockResult.Truth   => ConstantDescs.CD_boolean
      val parameterTypes = natives.natives(name).parameters.map {
        case NativePlace.NaturalList(_) => naturalListElements
        case _                       => bigInteger
      }
      MethodTypeDesc.of(resultType, parameterTypes*)

    /** The type of a generated function's static method: its operands, each
      * a value (a `BigInteger`, a `NarrowList` or a `java.lang.Boolean`,
      * typed `Object`), then the memo of the run before the call
      * (`NarrowMemo`) and the stop signal, in the slots after them, to its
      * value with the memo after the call (`NarrowMemo.Returned`) or null.
      * The memo and the stop come last so that a call pushes them after its
      * arguments' code has run (`generatedCalled`), the memo as the
      * arguments' calls left it; pushed first, a chain of
      * calls n deep held n stops on the operand stack, and each branch's
      * frame of the stack map listed them all, so that the class's stack map
      * grew as the square of the depth, and at 3,000 to 4,000 calls deep the
      * JVM failed with an internal error in its metaspace defining the class
      * (`metaspaceArena.cpp:85`, measured 2026-11-19).
      */
    private def generatedMethodType(parameters: Int): MethodTypeDesc =
      MethodTypeDesc.of(memoReturned, (Vector.fill(parameters)(objectClass) :+ memo :+ stopSignal)*)

    /** The type of a block's static method: the stop signal and the memo
      * before the run to the block's natural with the memo after it, or null,
      * the value checked to be a natural before it returns (`naturalChecked`).
      */
    private val blockMethodType: MethodTypeDesc = MethodTypeDesc.of(memoReturned, stopSignal, memo)

    private val functionNumbers: Map[(Instruction, Boolean), Int] =
      functions.zipWithIndex.map { case ((function, recursion, _), number) => ((function, recursion), number) }.toMap

    private def parameterCount(function: Instruction, recursion: Boolean): Int = function.layer match
      case Thunk(_, holes, _) => if recursion then holes.size - 1 else holes.size
      case other                    => throw IllegalStateException(s"a function is a thunk, not $other")

    /** Every literal the blocks and the functions read, with its constant,
      * in the order first met: a folded natural's computed, another literal's
      * decoded into a natural, a narrow list or a boolean (`constant`);
      * nothing when one does not decode.
      *
      * FIXME (found in a review, 2026-11-21; https://github.com/Atry/private-overlay/issues/1538):
      * a closed call of a boolean native, such as `equality 3 5`
      * written closed, is a literal (an operand the grammar reads closed) that
      * no decoder reads: `computed` folds only the natives whose result is a
      * natural, and `constant` decodes naturals, lists and boolean literals
      * under the booleans' criterion, not a native's call. So `literals` is
      * none and the whole class is refused, every block of the program with
      * it, a loss of every narrow block for one closed comparison. Candidate
      * fixes: fold a closed boolean native's call at compile time as a natural
      * one is folded, its result a `NarrowConstant.Truth`; or refuse only the
      * blocks that read the literal.
      */
    private val literals: Option[Vector[(Instruction, NarrowConstant)]] =
      val all = (blocks ++ functions.map(_._3)).flatMap(literalsOf).distinctBy(_._1)
      val read = all.map((literal, value) => value.map(NarrowConstant.Natural(_)).orElse(constant(literal)).map((literal, _)))
      Option.when(read.forall(_.isDefined))(read.flatten)

    /** The literals of the expression, in preorder, the parts left to right,
      * a closed natural read in place. Stack-safe: a loop over the parts
      * still to walk.
      */
    private def literalsOf(expression: NarrowExpression[Instruction]): Vector[(Instruction, Option[BigInt])] =
      @scala.annotation.tailrec
      def walked(
          pending: List[NarrowExpression[Instruction]],
          made: Vector[(Instruction, Option[BigInt])]
      ): Vector[(Instruction, Option[BigInt])] =
        pending match
          case Nil => made
          case next :: rest =>
            next match
              case NarrowExpression.Literal(literal)       => walked(rest, made :+ (literal, None))
              case NarrowExpression.Folded(literal, value) => walked(rest, made :+ (literal, Some(value)))
              case NarrowExpression.ClosedCode(code, environment) =>
                walked(rest, made :+ (NarrowBlockCompilation.instantiated(code, environment), None))
              case NarrowExpression.Value(closedValue)   => walked(reader.closed(closedValue).toList ::: rest, made)
              case NarrowExpression.Variable(_)          => walked(rest, made)
              case NarrowExpression.Native(_, arguments) => walked(arguments.toList ::: rest, made)
              case NarrowExpression.PartialApplication(partial, _) =>
                throw IllegalStateException(s"a partial application the reader did not expand: $partial")
              case NarrowExpression.Call(_, arguments)          => walked(arguments.toList ::: rest, made)
              case NarrowExpression.SelfCall(arguments)         => walked(arguments.toList ::: rest, made)
              case NarrowExpression.RecursionCall(_, arguments) => walked(arguments.toList ::: rest, made)
              case NarrowExpression.Branch(scrutinee, zero, _, even, _, odd) =>
                walked(scrutinee :: zero :: even :: odd :: rest, made)
              case NarrowExpression.ListBranch(scrutinee, nil, _, _, cons) => walked(scrutinee :: nil :: cons :: rest, made)
              case NarrowExpression.Filtered(value, _)                     => walked(value :: rest, made)
              case NarrowExpression.Select(scrutinee, whenTrue, whenFalse) =>
                walked(scrutinee :: whenTrue :: whenFalse :: rest, made)
              case NarrowExpression.Let(_, value, body) => walked(value :: body :: rest, made)
      walked(List(expression), Vector.empty)

    /** Why the expressions cannot be emitted, the first reason in reading
      * order (preorder, the parts left to right, a closed natural read in
      * place): a native call that is neither a constructor of the binary
      * naturals nor a `StaticBlockMethod` of as many places, or a closed
      * natural that does not read; none when every part can be emitted.
      * Stack-safe: a loop over the parts still to walk.
      */
    private def firstUnsupported(expressions: Vector[NarrowExpression[Instruction]]): Option[String] =
      @scala.annotation.tailrec
      def walked(pending: List[NarrowExpression[Instruction]]): Option[String] =
        pending match
          case Nil => None
          case next :: rest =>
            next match
              case NarrowExpression.Native(name, arguments) =>
                if !NarrowBlockCompilation.operations.contains((name, arguments.size)) && staticMethod(name, arguments.size).isEmpty
                then Some(s"the native $name of ${arguments.size} operands has no static method a block can call")
                else if !operandsLicensed(name, arguments) then
                  Some(s"an operand of the native $name is not known to be of the representation its place declares")
                else walked(arguments.toList ::: rest)
              case NarrowExpression.Value(closedValue) =>
                reader.closed(closedValue) match
                  case Some(read) => walked(read :: rest)
                  case None       => Some(s"a closed natural does not read: $closedValue")
              case NarrowExpression.Call(_, arguments) => walked(arguments.toList ::: rest)
              case NarrowExpression.PartialApplication(partial, _) =>
                throw IllegalStateException(s"a partial application the reader did not expand: $partial")
              case NarrowExpression.SelfCall(arguments)         => walked(arguments.toList ::: rest)
              case NarrowExpression.RecursionCall(_, arguments) => walked(arguments.toList ::: rest)
              case NarrowExpression.Branch(scrutinee, zero, _, even, _, odd) =>
                walked(scrutinee :: zero :: even :: odd :: rest)
              case NarrowExpression.ListBranch(scrutinee, nil, _, _, cons) => walked(scrutinee :: nil :: cons :: rest)
              case NarrowExpression.Filtered(value, _)                     => walked(value :: rest)
              case NarrowExpression.Select(scrutinee, whenTrue, whenFalse) => walked(scrutinee :: whenTrue :: whenFalse :: rest)
              case NarrowExpression.Let(_, value, body)                    => walked(value :: body :: rest)
              case NarrowExpression.Literal(_) | NarrowExpression.Folded(_, _) | NarrowExpression.ClosedCode(_, _) |
                  NarrowExpression.Variable(_) =>
                walked(rest)
      walked(expressions.toList)

    /** The class defined and its instances, one for each block; none, with
      * the reason, when a literal does not decode, a part cannot be emitted
      * (`firstUnsupported`), or a method could exceed the JVM's limit on a
      * method's code (`oversized`).
      */
    def defined(): Either[String, Vector[NarrowBlockProgram]] =
      checked.map { decodedLiterals =>
        val constants: Vector[AnyRef] = decodedLiterals.map((_, constant) => constant.runtimeValue)
        val lookup = MethodHandles.lookup()
        val hidden = lookup.defineHiddenClassWithClassData(bytes(decodedLiterals), java.util.List.of(constants*), true)
        val constructor = hidden.lookupClass().getDeclaredConstructor(classOf[Int])
        blocks.indices.toVector.map(number =>
          constructor.newInstance(Integer.valueOf(number)) match
            case program: NarrowBlockProgram => program
            case other => throw IllegalStateException(s"the generated class is no narrow block: $other")
        )
      }

    /** The class file `defined` defines; none, with the reason, as there. */
    def classFile(): Either[String, Array[Byte]] = checked.map(bytes)

    /** The literals decoded, when the class can be built. */
    private def checked: Either[String, Vector[(Instruction, NarrowConstant)]] =
      for
        decodedLiterals <- literals.toRight("a literal does not decode")
        _ <- firstUnsupported(blocks ++ functions.map(_._3)).toLeft(())
        _ <- oversized.toLeft(())
      yield decodedLiterals

    /** The class's bytes over the decoded literals, which its data holds in
      * that order: with the debugging attributes of `lines`, the `SourceFile`
      * and, for blocks from several files, the `SourceDebugExtension`, and a
      * line at the start of each block's method that has a place.
      */
    private def bytes(decodedLiterals: Vector[(Instruction, NarrowConstant)]): Array[Byte] =
      val literalIndex = decodedLiterals.zipWithIndex.map { case ((literal, constant), position) => literal -> (position, constant) }.toMap
      val resolver = ClassHierarchyResolver
        .defaultResolver()
        .orElse(ClassHierarchyResolver.ofClassLoading(getClass.getClassLoader))
      ClassFile
        .of(ClassFile.ClassHierarchyResolverOption.of(resolver))
        .build(
          generatedClass,
          (classBuilder: ClassBuilder) =>
            classBuilder
              .withFlags(ClassFile.ACC_PUBLIC | ClassFile.ACC_FINAL)
              .withInterfaceSymbols(programInterface)
            lines.foreach(found =>
              classBuilder.`with`(SourceFileAttribute.of(found.sourceFile))
              found.sourceMap.foreach(written =>
                classBuilder.`with`(SourceDebugExtensionAttribute.of(written.getBytes(java.nio.charset.StandardCharsets.UTF_8)))
              )
            )
            classBuilder.withField("block", ConstantDescs.CD_int, ClassFile.ACC_PRIVATE | ClassFile.ACC_FINAL)
            classBuilder.withMethodBody(
              ConstantDescs.INIT_NAME,
              MethodTypeDesc.of(ConstantDescs.CD_void, ConstantDescs.CD_int),
              ClassFile.ACC_PUBLIC,
              (code: CodeBuilder) =>
                code
                  .aload(0)
                  .invokespecial(objectClass, ConstantDescs.INIT_NAME, ConstantDescs.MTD_void)
                  .aload(0)
                  .iload(1)
                  .putfield(generatedClass, "block", ConstantDescs.CD_int)
                  .return_()
                ()
            )
            classBuilder.withMethodBody(
              "computed",
              MethodTypeDesc.of(memoReturned, stopSignal, memo),
              ClassFile.ACC_PUBLIC,
              (code: CodeBuilder) =>
                blocks.indices.foreach { number =>
                  val next = code.newLabel()
                  code.aload(0).getfield(generatedClass, "block", ConstantDescs.CD_int)
                  code.loadConstant(Integer.valueOf(number))
                  code.if_icmpne(next)
                  code.aload(1).aload(2)
                  code.invokestatic(generatedClass, s"block$number", blockMethodType)
                  code.areturn()
                  code.labelBinding(next)
                }
                code.aconst_null().areturn()
                ()
            )
            blocks.zipWithIndex.foreach { (expression, number) =>
              classBuilder.withMethodBody(
                s"block$number",
                blockMethodType,
                ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC,
                (code: CodeBuilder) =>
                  lines.flatMap(_.blockLines(number)).foreach(line => code.lineNumber(line))
                  val emission = Emission(code, literalIndex, None, Map.empty, Set.empty, blockMemoSlot + 1, 0, blockMemoSlot)
                  emission.emitted(expression)
                  if !emission.knownNatural(expression) then naturalChecked(code)
                  code.aload(blockMemoSlot).swap()
                  code.invokevirtual(memo, "returned", MethodTypeDesc.of(memoReturned, objectClass))
                  code.areturn()
                  ()
              )
            }
            functions.foreach { (function, recursion, body) =>
              val number = functionNumbers((function, recursion))
              val parameters = parameterCount(function, recursion)
              val firstParameter = if recursion then 1 else 0
              classBuilder.withMethodBody(
                s"function$number",
                generatedMethodType(parameters),
                ClassFile.ACC_PUBLIC | ClassFile.ACC_STATIC,
                (code: CodeBuilder) =>
                  val memoSlot = parameters
                  val stopSlot = parameters + 1
                  val keySlot = parameters + 2
                  if recursion then
                    stopPolled(code, stopSlot)
                    memoLookedUp(code, number, parameters, memoSlot, keySlot)
                  val slots = (0 until parameters).map(position => (firstParameter + position, position)).toMap
                  Emission(code, literalIndex, Option.when(recursion)((number, parameters)), slots, Set.empty, keySlot + 1, stopSlot, memoSlot)
                    .emitted(body)
                  code.aload(memoSlot).swap()
                  if recursion then
                    code.aload(keySlot)
                    code.invokevirtual(memo, "recordedReturn", MethodTypeDesc.of(memoReturned, objectClass, memoKey))
                  else code.invokevirtual(memo, "returned", MethodTypeDesc.of(memoReturned, objectClass))
                  code.areturn()
                  ()
              )
            }
        )

    /** Why a method of the class could exceed the JVM's limit on a
      * method's code, 65,535 bytes (`maximumCodeLength`), by the bounds of
      * `codeSizeBound`; none when every method is within it. A block is one
      * method, its expression emitted whole into it, so a closed natural
      * nested deeply enough would overflow it: measured 2026-11-17, a chain
      * of native plus over literals takes 5 to 21 bytes a level, and at depth
      * 20,000 the class build threw `IllegalArgumentException: Code length
      * 100003 is outside the allowed range`.
      * Refused here,
      * the block is left to the general reading, as a block that does not
      * read is.
      */
    private def oversized: Option[String] =
      val methods =
        blocks.zipWithIndex.map((expression, number) =>
          (s"block$number", codeSizeBound(expression) + naturalCheckBound + methodOverheadBound)
        ) ++
          functions.map((function, recursion, body) =>
            (
              s"function${functionNumbers((function, recursion))}",
              codeSizeBound(body) + methodOverheadBound +
                (if recursion then memoLookupBound + memoArgumentBound * parameterCount(function, recursion) else 0L)
            )
          ) :+ ("computed", blocks.size.toLong * dispatchBound + methodOverheadBound)
      methods.collectFirst {
        case (name, bound) if bound > maximumCodeLength =>
          s"the method $name may take up to $bound bytes of code, beyond the JVM's $maximumCodeLength"
      }

    /** An upper bound on the bytes of code `Emission` writes for the
      * expression: each part's instructions at their widest form (a
      * constant pool reference of three bytes, a local variable's load or
      * store with its `wide` prefix, a branch widened to `goto_w` as the
      * class file writer does when its offset does not fit), a closed natural
      * read in place. Stack-safe: a loop over the parts still to walk.
      */
    private def codeSizeBound(expression: NarrowExpression[Instruction]): Long =
      @scala.annotation.tailrec
      def walked(pending: List[NarrowExpression[Instruction]], total: Long): Long =
        pending match
          case Nil => total
          case next :: rest =>
            next match
              case NarrowExpression.Literal(_) | NarrowExpression.Folded(_, _) | NarrowExpression.ClosedCode(_, _) =>
                walked(rest, total + 3)
              case NarrowExpression.Value(closedValue) =>
                reader.closed(closedValue) match
                  case Some(read) => walked(read :: rest, total)
                  case None       => throw IllegalStateException(s"a closed natural does not read: $closedValue")
              case NarrowExpression.Variable(_) => walked(rest, total + 4)
              case NarrowExpression.Native(name, arguments) =>
                val operation = NarrowBlockCompilation.operations.get((name, arguments.size)).fold(3)(_.codeSizeBound)
                val listElements = if takesNaturalList(name) then arguments.size * listElementsBound else 0L
                walked(arguments.toList ::: rest, total + operation + truthBoxingBound + arguments.size * naturalCheckBound + listElements)
              case NarrowExpression.PartialApplication(partial, _) =>
                throw IllegalStateException(s"a partial application the reader did not expand: $partial")
              case NarrowExpression.Call(_, arguments)          => walked(arguments.toList ::: rest, total + callBound)
              case NarrowExpression.SelfCall(arguments)         => walked(arguments.toList ::: rest, total + callBound)
              case NarrowExpression.RecursionCall(_, arguments) => walked(arguments.toList ::: rest, total + callBound)
              case NarrowExpression.Branch(scrutinee, zero, _, even, _, odd) =>
                walked(scrutinee :: zero :: even :: odd :: rest, total + branchBound + naturalCheckBound)
              case NarrowExpression.ListBranch(scrutinee, nil, _, _, cons) =>
                walked(scrutinee :: nil :: cons :: rest, total + listBranchBound + naturalCheckBound)
              case NarrowExpression.Filtered(value, _)  => walked(value :: rest, total + naturalCheckBound)
              case NarrowExpression.Select(scrutinee, whenTrue, whenFalse) =>
                walked(scrutinee :: whenTrue :: whenFalse :: rest, total + selectBound + naturalCheckBound)
              case NarrowExpression.Let(_, value, body) => walked(value :: body :: rest, total + 4)
      walked(List(expression), 0)

    /** A native's boxing of a JVM `boolean` result (`Boolean.valueOf`, an
      * `invokestatic`), counted at every native's call as an upper bound.
      */
    private val truthBoxingBound: Long = 3

    /** A boolean's branch (`Emission.steps`' `Select`) besides its parts and
      * its scrutinee's check, which is as long as a natural's:
      * `invokevirtual` of `booleanValue`, an `ifeq` widened to eight bytes, a
      * `goto` widened to `goto_w`.
      */
    private val selectBound: Long = 3 + 8 + 5

    /** A list branch (`Emission.steps`' `ListBranch`) besides its parts and
      * its scrutinee's check, which is as long as a natural's: the
      * scrutinee's store with `wide`; its load, `invokevirtual` of `nil` and
      * an `ifeq` widened to eight bytes; a `goto` widened to `goto_w`; and for
      * each of the head and the tail a load and a store with `wide` and an
      * `invokevirtual`.
      */
    private val listBranchBound: Long = 4 + (4 + 3 + 8) + 5 + 2 * (4 + 3 + 4)

    /** A value's check that it is a natural (`naturalChecked`): `dup`,
      * `instanceof`, an `ifne` widened to eight bytes, `aconst_null`,
      * `areturn`, `checkcast`.
      */
    private val naturalCheckBound: Long = 1 + 3 + 8 + 1 + 1 + 3

    /** The `invokevirtual` of `NarrowList.remaining` at an operand of a
      * `NativePlace.NaturalList`, counted at every operand of such a native as
      * an upper bound.
      */
    private val listElementsBound: Long = 3

    /** The JVM's limit on a method's code, in bytes. */
    private val maximumCodeLength: Long = 65535

    /** A generated call (`generatedCalled`) besides its arguments: the
      * memo's and the stop's `aload`s with their `wide` prefixes,
      * `invokestatic`, `dup`, `ifnonnull` widened to an inverted branch over a
      * `goto_w`, `pop`, `aconst_null`, `areturn`, then `dup`, the
      * `invokevirtual` of `memo`, its `astore` with `wide` and the
      * `invokevirtual` of `value`.
      */
    private val callBound: Long = 2 * 4 + 3 + 1 + 8 + 1 + 1 + 1 + 1 + 3 + 4 + 3

    /** A branch (`Emission.steps`' `Branch`) besides its parts: two stores
      * and four loads with `wide`, three `invokevirtual`s, two `iconst`s, two
      * `ifne`s widened to eight bytes and two `goto`s widened to `goto_w`.
      */
    private val branchBound: Long = 2 * 4 + 4 * 4 + 3 * 3 + 2 * 1 + 2 * 8 + 2 * 5

    /** A method besides its expression: a recursion's poll (`stopPolled`,
      * the stop's `aload` with its `wide` prefix, `invokeinterface`, a widened `ifeq`, `aconst_null`,
      * `areturn`), the return (the memo's `aload` with `wide`, `swap`, the
      * key's `aload` with `wide`, an `invokevirtual`) and the closing
      * `areturn`, rounded up; a recursion's memo lookup is
      * `memoLookupBound` more.
      */
    private val methodOverheadBound: Long = 48

    /** A recursion's memo lookup (`memoLookedUp`) besides its parameters:
      * `getstatic`, the number loaded by `ldc_w`, `invokevirtual`, the key's
      * `astore` and two `aload`s with `wide`, `invokevirtual`, `dup`, an
      * `ifnull` widened to eight bytes, the memo's `aload` with `wide`,
      * `swap`, `invokevirtual`, `areturn`, `pop`; and for each parameter
      * (`memoArgumentBound`) its `aload` with `wide` and an `invokevirtual`.
      */
    private val memoLookupBound: Long = 3 + 3 + 3 + 3 * 4 + 3 + 1 + 8 + 4 + 1 + 3 + 1 + 1

    private val memoArgumentBound: Long = 4 + 3

    /** One block's dispatch in `computed`: `aload_0`, `getfield`, its number
      * loaded, a widened `if_icmpne`, `aload_1`, `aload_2`, `invokestatic`,
      * `areturn`, rounded up.
      */
    private val dispatchBound: Long = 32

    /** A recursion's poll, at its method's entry: return null, the
      * bytecode's "nothing", when the stop signal in its slot asks for a
      * stop. Null, not a typed outcome: a generated method returns its value
      * as a reference, and a stop is one more value of that return;
      * an outcome object would cost an allocation on every recursive call's
      * return, the hot path of the block, to carry a stop that comes once.
      * It stays in the generated code: the one boundary that reads it is
      * `NarrowBlockProgram.run`, which gives an `Option`.
      */
    private def stopPolled(code: CodeBuilder, stopSlot: Int): Unit =
      val going = code.newLabel()
      code.aload(stopSlot).invokeinterface(stopSignal, "stopRequested", MethodTypeDesc.of(ConstantDescs.CD_boolean))
      code.ifeq(going)
      code.aconst_null().areturn()
      code.labelBinding(going)
      ()

    /** The slot of a block's method's memo, its parameter after the stop
      * signal.
      */
    private val blockMemoSlot: Int = 1

    /** A recursion's memo lookup, at its method's entry after the poll
      * ([[NarrowMemo]]): the call's key, the recursion's number with its parameters' values
      * (`NarrowMemo.Key`), stored in its slot for the record made on return;
      * the value recorded under it, when the run has one, returned at once
      * with the memo unchanged. A call in progress has no record, so a
      * re-entered call is evaluated as without the memo.
      */
    private def memoLookedUp(code: CodeBuilder, number: Int, parameters: Int, memoSlot: Int, keySlot: Int): Unit =
      val missed = code.newLabel()
      code.getstatic(memoModule, "MODULE$", memoModule)
      code.loadConstant(Integer.valueOf(number))
      code.invokevirtual(memoModule, "key", MethodTypeDesc.of(memoKey, ConstantDescs.CD_int))
      (0 until parameters).foreach { position =>
        code.aload(position)
        code.invokevirtual(memoKey, "withArgument", MethodTypeDesc.of(memoKey, objectClass))
      }
      code.astore(keySlot)
      code.aload(memoSlot).aload(keySlot)
      code.invokevirtual(memo, "found", MethodTypeDesc.of(objectClass, memoKey))
      code.dup().ifnull(missed)
      code.aload(memoSlot).swap()
      code.invokevirtual(memo, "returned", MethodTypeDesc.of(memoReturned, objectClass))
      code.areturn()
      code.labelBinding(missed)
      code.pop()
      ()

    /** The check of the value on the top of the stack where the code reads
      * it as a natural: a `BigInteger` is cast to its type and left on the
      * stack; any other value, a narrow list, makes the method return null,
      * no value, as a stop does (`NarrowBlockProgram.run` tells the two
      * apart). Every generated call returns at once on a null
      * (`generatedCalled`), so no value travels up to the block's method. A
      * value is never null here: a null is returned as soon as it is made.
      */
    private def naturalChecked(code: CodeBuilder): Unit = representationChecked(code, bigInteger)

    /** The check of the value on the top of the stack where a list branch
      * reads it as a list, as `naturalChecked` checks a natural: a
      * `NarrowList` is cast to its type, any other value makes the method
      * return null.
      */
    private def listChecked(code: CodeBuilder): Unit = representationChecked(code, narrowList)

    /** The check of the value on the top of the stack where the code reads
      * it as a boolean, as `naturalChecked` checks a natural: a
      * `java.lang.Boolean` is cast to its type, any other value makes the
      * method return null.
      */
    private def truthChecked(code: CodeBuilder): Unit = representationChecked(code, boxedTruth)

    /** The check of a value read in the representation given. */
    private def checkedAs(code: CodeBuilder, representation: NarrowRepresentation): Unit = representation match
      case NarrowRepresentation.Natural => naturalChecked(code)
      case NarrowRepresentation.ListOf  => listChecked(code)
      case NarrowRepresentation.Truth   => truthChecked(code)

    private def representationChecked(code: CodeBuilder, representation: ClassDesc): Unit =
      val fits = code.newLabel()
      code.dup().instanceOf(representation)
      code.ifne(fits)
      code.aconst_null().areturn()
      code.labelBinding(fits)
      code.checkcast(representation)
      ()

    /** The call of a generated function, as emission steps: the arguments'
      * steps (`pushed`), then the memo and the stop signal of the calling
      * method's slots pushed, then the method invoked and a null it returns, a
      * stop, returned at once from the calling method; otherwise the memo
      * after the call stored in the calling method's slot and the call's value
      * left on the stack. The null returned is a
      * fresh `aconst_null`, not the call's result: the result is typed
      * `Object`, which a block's method, returning a `BigInteger`, may not
      * return (the verifier's "Bad return type").
      */
    private def generatedCalled(code: CodeBuilder, memoSlot: Int, stopSlot: Int, method: String, arguments: Int)(
        pushed: List[EmissionStep]
    ): List[EmissionStep] =
      val going = code.newLabel()
      pushed ::: List(EmissionStep.emitting(() =>
        code.aload(memoSlot).aload(stopSlot)
        code.invokestatic(generatedClass, method, generatedMethodType(arguments))
        code.dup().ifnonnull(going)
        code.pop().aconst_null().areturn()
        code.labelBinding(going)
        code.dup().invokevirtual(memoReturned, "memo", MethodTypeDesc.of(memo)).astore(memoSlot)
        code.invokevirtual(memoReturned, "value", MethodTypeDesc.of(objectClass))
        ()
      ))

    /** A step of a method's emission, taken by `taken`, which gives the
      * steps that come in its place: an expression still to emit under its
      * emission (`EmissionStep.expression`, in place of its steps), or
      * bytecode to emit on the code builder (`EmissionStep.emitting`, in
      * place of nothing), such as what comes after an expression's parts (a
      * native's invoke after its operands). A function rather than an enum
      * of the two: a pattern match on a case that holds an `Emission` makes
      * Scala 3.10.0's pattern matcher load the sealed `CodeBuilder`'s JDK
      * subclasses and crash on a cyclic reference (`BufferedMethodBuilder`).
      */
    private final case class EmissionStep(taken: () => List[EmissionStep])

    private object EmissionStep:

      /** The expression emitted under the emission. */
      def expression(expression: NarrowExpression[Instruction], emission: Emission): EmissionStep =
        EmissionStep(() => emission.steps(expression))

      /** The bytecode `emitted` emits. */
      def emitting(emitted: () => Unit): EmissionStep =
        EmissionStep(() =>
          emitted()
          Nil
        )

    /** The steps taken in order, each step's own steps before the steps
      * after it.
      */
    @scala.annotation.tailrec
    private def emittedInOrder(pending: List[EmissionStep]): Unit =
      pending match
        case Nil          => ()
        case step :: rest => emittedInOrder(step.taken() ::: rest)

    /** The emission of one method's expressions: its literals' indexes in
      * the class's data with their constants, the recursion it is (its
      * number and parameters), the slot of each binder, the binders whose
      * value is known to be a natural (a branch's half, a let of a natural),
      * the next slot free, the stop signal's slot and the memo's slot.
      */
    private final case class Emission(
        code: CodeBuilder,
        literalIndex: Map[Instruction, (Int, NarrowConstant)],
        recursion: Option[(Int, Int)],
        slots: Map[Int, Int],
        naturalBinders: Set[Int],
        nextSlot: Int,
        stopSlot: Int,
        memoSlot: Int
    ):

      /** Whether the expression's value is a natural whatever the values of
        * the method's parameters, so that reading it as one needs no check
        * (`naturalChecked`): a natural literal, a folded natural, a native's
        * call of a natural, a closed natural that reads as one of these, a
        * value under a natural's filter (checked there), or a binder of
        * `naturalBinders`. A call, a parameter or a branch may give a list or
        * a boolean, and is checked.
        */
      def knownNatural(expression: NarrowExpression[Instruction]): Boolean = expression match
        case NarrowExpression.Literal(literal) => literalRepresentation(literal) == NarrowRepresentation.Natural
        case NarrowExpression.Folded(_, _)     => true
        case NarrowExpression.ClosedCode(closedCode, environment) =>
          literalRepresentation(NarrowBlockCompilation.instantiated(closedCode, environment)) == NarrowRepresentation.Natural
        case NarrowExpression.Value(closedValue) =>
          reader.closed(closedValue).exists {
            case NarrowExpression.Literal(literal) => literalRepresentation(literal) == NarrowRepresentation.Natural
            case NarrowExpression.Folded(_, _)     => true
            case NarrowExpression.Native(name, arguments) => nativeResult(name, arguments.size) == StaticBlockResult.Natural
            case _                                 => false
          }
        case NarrowExpression.Native(name, arguments) => nativeResult(name, arguments.size) == StaticBlockResult.Natural
        case NarrowExpression.Filtered(_, NarrowRepresentation.Natural) => true
        case NarrowExpression.Variable(binder) => naturalBinders.contains(binder)
        case _                                  => false

      /** Whether the expression's value is of the representation whatever
        * the values of the method's parameters, so that a filter of it needs
        * no check: a natural as `knownNatural` reads one; a literal of the
        * representation, a value under its filter, or a boolean native's call
        * for the others.
        */
      private def known(expression: NarrowExpression[Instruction], representation: NarrowRepresentation): Boolean =
        representation match
          case NarrowRepresentation.Natural => knownNatural(expression)
          case _ =>
            expression match
              case NarrowExpression.Literal(literal)                => literalRepresentation(literal) == representation
              case NarrowExpression.Filtered(_, filtered)           => filtered == representation
              case NarrowExpression.Native(name, arguments) =>
                representation == NarrowRepresentation.Truth && nativeResult(name, arguments.size) == StaticBlockResult.Truth
              case _ => false

      private def literalRepresentation(literal: Instruction): NarrowRepresentation =
        literalIndex(literal)._2 match
          case NarrowConstant.Natural(_) => NarrowRepresentation.Natural
          case NarrowConstant.ListOf(_)  => NarrowRepresentation.ListOf
          case NarrowConstant.Truth(_)   => NarrowRepresentation.Truth

      /** The JVM convention of a native call's result: a binary naturals'
        * constructor's is a natural, a static method's its own.
        */
      private def nativeResult(name: NativeName, operands: Int): StaticBlockResult =
        if NarrowBlockCompilation.operations.contains((name, operands)) then StaticBlockResult.Natural
        else
          staticMethod(name, operands)
            .getOrElse(throw IllegalStateException(s"a native with no operation and no static method: $name"))
            .result

      /** The expression's bytecode, emitted on the code builder. Stack-safe:
        * a loop over a list of steps (`EmissionStep`), each expression
        * replaced by its parts' steps and the bytecode around them, so an
        * expression nested as deep as a program's term is emitted without a
        * JVM frame per level.
        */
      def emitted(expression: NarrowExpression[Instruction]): Unit =
        emittedInOrder(List(EmissionStep.expression(expression, this)))

      /** The steps that emit the expression, in the order of its bytecode. */
      def steps(expression: NarrowExpression[Instruction]): List[EmissionStep] = expression match
        case NarrowExpression.Literal(literal) =>
          val (position, constant) = literalIndex(literal)
          val constantType = constant match
            case NarrowConstant.Natural(_) => bigInteger
            case NarrowConstant.ListOf(_)  => narrowList
            case NarrowConstant.Truth(_)   => boxedTruth
          List(EmissionStep.emitting(() =>
            code.ldc(
              DynamicConstantDesc.ofNamed(
                ConstantDescs.BSM_CLASS_DATA_AT,
                ConstantDescs.DEFAULT_NAME,
                constantType,
                Integer.valueOf(position)
              )
            )
            ()
          ))
        case NarrowExpression.Folded(literal, _) => steps(NarrowExpression.Literal(literal))
        case NarrowExpression.ClosedCode(closedCode, environment) =>
          List(EmissionStep.expression(NarrowExpression.Literal(NarrowBlockCompilation.instantiated(closedCode, environment)), this))
        case NarrowExpression.Value(closedValue) =>
          reader.closed(closedValue) match
            case Some(read) => List(EmissionStep.expression(read, this))
            case None       => throw IllegalStateException(s"a closed natural does not read: $closedValue")
        case NarrowExpression.Variable(binder) =>
          List(EmissionStep.emitting(() =>
            code.aload(slots(binder))
            ()
          ))
        case NarrowExpression.Filtered(value, representation) =>
          EmissionStep.expression(value, this) :: (
            if known(value, representation) then Nil
            else List(EmissionStep.emitting(() => checkedAs(code, representation)))
          )
        case NarrowExpression.Native(name, arguments) =>
          nativeOperandSteps(name, arguments) :+ EmissionStep.emitting(() =>
            NarrowBlockCompilation.operations.get((name, arguments.size)) match
              case Some(operation) => operation.emitted(code, bigInteger)
              case None =>
                val method = staticMethod(name, arguments.size)
                  .getOrElse(throw IllegalStateException(s"a native with no operation and no static method: $name"))
                code.invokestatic(ClassDesc.of(method.className), method.methodName, nativeMethodType(name, method.result))
                method.result match
                  case StaticBlockResult.Natural => ()
                  case StaticBlockResult.Truth =>
                    code.invokestatic(boxedTruth, "valueOf", MethodTypeDesc.of(boxedTruth, ConstantDescs.CD_boolean))
                    ()
          )
        case NarrowExpression.PartialApplication(partial, _) => throw IllegalStateException(s"a partial application the reader did not expand: $partial")
        case NarrowExpression.Call(function, arguments) =>
          generatedCalled(code, memoSlot, stopSlot, s"function${functionNumbers((function, false))}", arguments.size)(operandSteps(arguments))
        case NarrowExpression.SelfCall(arguments) =>
          val (number, parameters) = recursion.getOrElse(throw IllegalStateException("a self call outside a recursion"))
          generatedCalled(code, memoSlot, stopSlot, s"function$number", parameters)(operandSteps(arguments))
        case NarrowExpression.RecursionCall(body, arguments) =>
          generatedCalled(code, memoSlot, stopSlot, s"function${functionNumbers((body, true))}", arguments.size)(operandSteps(arguments))
        case NarrowExpression.Let(binder, value, body) =>
          val bodyNaturals = if knownNatural(value) then naturalBinders + binder else naturalBinders - binder
          List(
            EmissionStep.expression(value, this),
            EmissionStep.emitting(() =>
              code.astore(nextSlot)
              ()
            ),
            EmissionStep.expression(
              body,
              copy(slots = slots.updated(binder, nextSlot), naturalBinders = bodyNaturals, nextSlot = nextSlot + 1)
            )
          )
        case NarrowExpression.Branch(scrutinee, zero, evenHalf, even, oddHalf, odd) =>
          val scrutineeSlot = nextSlot
          val halfSlot = nextSlot + 1
          val inner = copy(nextSlot = nextSlot + 2)
          val nonZero = code.newLabel()
          val oddCase = code.newLabel()
          val end = code.newLabel()
          val scrutineeNatural = knownNatural(scrutinee)
          List(
            EmissionStep.expression(scrutinee, this),
            EmissionStep.emitting(() =>
              if !scrutineeNatural then naturalChecked(code)
              code.astore(scrutineeSlot)
              code.aload(scrutineeSlot).invokevirtual(bigInteger, "signum", MethodTypeDesc.of(ConstantDescs.CD_int))
              code.ifne(nonZero)
              ()
            ),
            EmissionStep.expression(zero, inner),
            EmissionStep.emitting(() =>
              code.goto_(end)
              code.labelBinding(nonZero)
              code.aload(scrutineeSlot).iconst_1().invokevirtual(bigInteger, "shiftRight", MethodTypeDesc.of(bigInteger, ConstantDescs.CD_int))
              code.astore(halfSlot)
              code.aload(scrutineeSlot).iconst_0().invokevirtual(bigInteger, "testBit", MethodTypeDesc.of(ConstantDescs.CD_boolean, ConstantDescs.CD_int))
              code.ifne(oddCase)
              ()
            ),
            EmissionStep.expression(
              even,
              inner.copy(slots = inner.slots.updated(evenHalf, halfSlot), naturalBinders = inner.naturalBinders + evenHalf)
            ),
            EmissionStep.emitting(() =>
              code.goto_(end)
              code.labelBinding(oddCase)
              ()
            ),
            EmissionStep.expression(
              odd,
              inner.copy(slots = inner.slots.updated(oddHalf, halfSlot), naturalBinders = inner.naturalBinders + oddHalf)
            ),
            EmissionStep.emitting(() =>
              code.labelBinding(end)
              ()
            )
          )
        case NarrowExpression.ListBranch(scrutinee, nil, headBinder, tailBinder, cons) =>
          val scrutineeSlot = nextSlot
          val headSlot = nextSlot + 1
          val tailSlot = nextSlot + 2
          val inner = copy(nextSlot = nextSlot + 3)
          val consCase = code.newLabel()
          val end = code.newLabel()
          List(
            EmissionStep.expression(scrutinee, this),
            EmissionStep.emitting(() =>
              listChecked(code)
              code.astore(scrutineeSlot)
              code.aload(scrutineeSlot).invokevirtual(narrowList, "nil", MethodTypeDesc.of(ConstantDescs.CD_boolean))
              code.ifeq(consCase)
              ()
            ),
            EmissionStep.expression(nil, inner),
            EmissionStep.emitting(() =>
              code.goto_(end)
              code.labelBinding(consCase)
              code.aload(scrutineeSlot).invokevirtual(narrowList, "head", MethodTypeDesc.of(bigInteger))
              code.astore(headSlot)
              code.aload(scrutineeSlot).invokevirtual(narrowList, "tail", MethodTypeDesc.of(narrowList))
              code.astore(tailSlot)
              ()
            ),
            EmissionStep.expression(
              cons,
              inner.copy(
                slots = inner.slots.updated(headBinder, headSlot).updated(tailBinder, tailSlot),
                naturalBinders = inner.naturalBinders + headBinder - tailBinder
              )
            ),
            EmissionStep.emitting(() =>
              code.labelBinding(end)
              ()
            )
          )
        case NarrowExpression.Select(scrutinee, whenTrue, whenFalse) =>
          val falseCase = code.newLabel()
          val end = code.newLabel()
          val scrutineeTruth = known(scrutinee, NarrowRepresentation.Truth)
          List(
            EmissionStep.expression(scrutinee, this),
            EmissionStep.emitting(() =>
              if !scrutineeTruth then truthChecked(code)
              code.invokevirtual(boxedTruth, "booleanValue", MethodTypeDesc.of(ConstantDescs.CD_boolean))
              code.ifeq(falseCase)
              ()
            ),
            EmissionStep.expression(whenTrue, this),
            EmissionStep.emitting(() =>
              code.goto_(end)
              code.labelBinding(falseCase)
              ()
            ),
            EmissionStep.expression(whenFalse, this),
            EmissionStep.emitting(() =>
              code.labelBinding(end)
              ()
            )
          )

      /** The steps that push the operands, in order. */
      private def operandSteps(arguments: Vector[NarrowExpression[Instruction]]): List[EmissionStep] =
        arguments.toList.map(EmissionStep.expression(_, this))

      /** The steps that push a native's operands, in order, each checked to
        * be a natural (`naturalChecked`) unless it is known to be one.
        *
        * The check stands where no filter is written: a function's bare
        * parameter, a call's result, as the operand `s t` of a fold's
        * `plus h (s t)`. It is a run-time check at a natural read, which gives
        * no value on a narrow list so that the reader falls back and adds no
        * answer: the price of not working out in the host which binders
        * hold lists, which would be type information in the host
        * (`CONTRIBUTING.md`, "Types live only in the term"). It costs an `instanceof` and a
        * branch on every such operand at every call. It disappears where the
        * typed knowledge writes the filter `∥ binary_set true`
        * at the operand, which makes it known to be a natural.
        */
      private def naturalOperandSteps(arguments: Vector[NarrowExpression[Instruction]]): List[EmissionStep] =
        arguments.toList.flatMap(argument =>
          EmissionStep.expression(argument, this) ::
            (if knownNatural(argument) then Nil
             else
               List(EmissionStep.emitting(() =>
                 naturalChecked(code)
               )))
        )

      /** A native's operands as `naturalOperandSteps` emits them, but for
        * an operand at a place `NativePlace.NaturalList`: its elements are
        * passed. The operand is a literal decoded under the filter
        * `∥ list_type c` written in the term (`listDecoded`), which
        * `placeLicensed` has compared with the place; `listChecked` gives the
        * value its JVM type.
        */
      private def nativeOperandSteps(name: NativeName, arguments: Vector[NarrowExpression[Instruction]]): List[EmissionStep] =
        if !takesNaturalList(name) then naturalOperandSteps(arguments)
        else
          arguments.toList.zip(natives.natives(name).parameters).flatMap {
            case (argument, NativePlace.NaturalList(_)) =>
              List(
                EmissionStep.expression(argument, this),
                EmissionStep.emitting(() =>
                  listChecked(code)
                  code.invokevirtual(narrowList, "remaining", MethodTypeDesc.of(naturalListElements))
                  ()
                )
              )
            case (argument, _) => naturalOperandSteps(Vector(argument))
          }

/** The operations of the natives a narrow block calls. */
object NarrowBlockCompilation:

  /** The closed term of a code read at the closed terms of its slots.
    * Stack-safe: read on `scala.util.control.TailCalls`.
    */
  def instantiated(code: gezi.ir.Code, environment: Map[Int, Instruction]): Instruction =
    instantiation(code, environment).result

  private def instantiation(code: gezi.ir.Code, environment: Map[Int, Instruction]): TailRec[Instruction] =
    def both(left: gezi.ir.Code, right: gezi.ir.Code)(made: (Instruction, Instruction) => Instruction): TailRec[Instruction] =
      tailcall(instantiation(left, environment)).flatMap(instantiatedLeft =>
        tailcall(instantiation(right, environment)).map(made(instantiatedLeft, _))
      )
    code.layer match
      case Slot(slot) =>
        done(environment.getOrElse(slot, throw IllegalStateException(s"the slot $slot of a closed code has no term")))
      case Apply(function, argument) => both(function, argument)(Instruction.Apply(_, _))
      case Parallel(left, right)     => both(left, right)(Instruction.Parallel(_, _))
      case Choice(left, right)       => both(left, right)(Instruction.Choice(_, _))
      case Thunk(inner, holes, fillings) =>
        TailRecFolds.folded(fillings.toVector, Vector.empty[Instruction])((made, filling) => instantiation(filling, environment).map(made :+ _))
          .map(Instruction.Thunk(inner, holes, _))

  /** Each item read, in order; nothing at the first item that does not
    * read. A reading of `scala.util.control.TailCalls`, so that it is
    * stack-safe however deep each item's reading goes.
    */
  private[narrowblocks] def allRead[Item, Read](items: Vector[Item])(
      read: Item => TailRec[Option[Read]]
  ): TailRec[Option[Vector[Read]]] =
    TailRecFolds.folded[Item, Option[Vector[Read]]](items, Some(Vector.empty)) {
      case (None, _)         => done(None)
      case (Some(made), item) => read(item).map(_.map(made :+ _))
    }

  /** native_types' contract, λd.λr.λf.λx. (f (x ∥ d)) ∥ r, as the front
    * end writes it: a constructor under it, `arrow D R C`, is C on an
    * argument D admits, giving a value R admits, by β.
    */
  lazy val contract: Instruction =
    import gezi.frontend.Term.λ
    Defunctionalization.thunkInstruction(
      λ(domain => λ(range => λ(function => λ(argument => function(argument ∥ domain) ∥ range)))).deBruijnTerm(Map.empty)
    )

  /** A native's operation on its operands on the stack, leaving its result. */
  final case class Operation(method: String, extra: Option[Int], thenSetsBit: Boolean, refusesZero: Boolean):

    /** The bytes of code `emitted` writes, at most: the zero check when it
      * refuses zero (`dup`, the `invokevirtual` of `signum`, an `ifne`
      * widened to eight bytes, `pop`, `aconst_null`, `areturn`), the constant
      * loaded (`iconst` one byte, `bipush` two, `sipush` or an `ldc_w`
      * three), an `invokevirtual` or a `getstatic`, and `iconst_0` with an
      * `invokevirtual` when it sets the low bit.
      */
    def codeSizeBound: Int =
      val constant = extra.fold(0)(value =>
        if value >= -1 && value <= 5 then 1 else if value >= Byte.MinValue && value <= Byte.MaxValue then 2 else 3
      )
      (if refusesZero then 1 + 3 + 8 + 1 + 1 + 1 else 0) + constant + 3 + (if thenSetsBit then 4 else 0)

    /** The operation on the natural on the top of the stack. One that
      * refuses zero first makes the method return null, no value, when the
      * natural is zero, as a value read in a representation it does not have
      * does (`representationChecked`): `binary_even binary_zero` is no
      * canonical natural, so no `BigInteger` represents it, and the reader
      * falls back to the term. Compile-time folding refuses it the same way
      * (`computed`, `constructed`). Measured 2026-11-21: without the check the
      * block of a numeral with leading zeros of
      * `repeated_library_binary_domain_traps` (respelled, R = 4) computed the
      * leading zeros away, and the entry answered the point falsely.
      */
    def emitted(code: CodeBuilder, bigInteger: ClassDesc): Unit =
      if refusesZero then
        val positive = code.newLabel()
        code.dup().invokevirtual(bigInteger, "signum", MethodTypeDesc.of(ConstantDescs.CD_int))
        code.ifne(positive)
        code.pop().aconst_null().areturn()
        code.labelBinding(positive)
      extra match
        case Some(constant) =>
          code.loadConstant(Integer.valueOf(constant))
          code.invokevirtual(bigInteger, method, MethodTypeDesc.of(bigInteger, ConstantDescs.CD_int))
        case None =>
          if method == "ZERO" then code.getstatic(bigInteger, "ZERO", bigInteger)
          else code.invokevirtual(bigInteger, method, MethodTypeDesc.of(bigInteger, bigInteger))
      if thenSetsBit then
        code.iconst_0()
        code.invokevirtual(bigInteger, "setBit", MethodTypeDesc.of(bigInteger, ConstantDescs.CD_int))
      ()

  /** The operation of each of the binary naturals' constructors, the
    * framework's own natives, by its name and its operands' count. An
    * entry's natives are called through their `StaticBlockMethod`s.
    */
  val operations: Map[(NativeName, Int), Operation] = Map(
    (BinaryNaturalFamily.zeroNative, 0) -> Operation("ZERO", None, false, false),
    (BinaryNaturalFamily.evenNative, 1) -> Operation("shiftLeft", Some(1), false, true),
    (BinaryNaturalFamily.oddNative, 1)  -> Operation("shiftLeft", Some(1), true, false)
  )
